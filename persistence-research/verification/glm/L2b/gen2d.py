# r8 gen_cert2d.py — certificate generator for the one-far mixed closure (M*):
#   2^t 3^a 7^w = 10^L + A*10^q + K,  domain L > q >= qmin,  K = 9*S_low - 1,
#   t = t0 = v2(K) on the whole domain (qmin = max(3, t0+1) > t0).
# One JSONL certificate per (A, K) pair. Tree over classes (L mod ML, q mod MQ).
# The q = 3 slice of S_low = 1 is NOT covered here (separate v12-format 1-D certs
# with K = 9008/18008/27008); this tree covers q >= qmin.
#
# Output format (see notes/proof_attempt_glm_r8.md):
#   line 1: {"k":"meta","A":A,"K":K,"qmin":Q0}
#   internal: {"k":"i","p":par,"r":[rL,rq],"m":[ML,MQ],"c":[ids],"rest":{"q":p}|null}
#   leaf:     {"k":"l","p":par,"r":[rL,rq],"m":[ML,MQ],"a":[lo,hi],"w":[lo,hi],"x":...}
#     x = {"T0":p} | {"prime":p} | {"pin":qp} | {"sz":[a0,w0],"L":[[L,q],...]}
# Run: bash -c 'ulimit -v 3000000; python3 -I gen_cert2d.py S A'

import math, json, sys, os

MAXM = int(__import__('os').environ.get('MAXM', '2000000000'))
NODE_CAP = 400_000
KILL_SCAN = 10**9  # scan all primes < 50000 (region kills can come from weak-region primes)
COMBO_CAP = 4096
SPLIT_SCAN = 50
SPLIT_CAP = 256
SET_CAP = 1_000_000

def vp(n, p):
    c = 0
    while n % p == 0:
        n //= p; c += 1
    return c

def smooth237(x):
    for p in (2, 3, 7):
        while x % p == 0:
            x //= p
    return x == 1

def primes_upto(b):
    s = [True] * b
    for i in range(2, int(b ** 0.5) + 1):
        if s[i]:
            for j in range(i * i, b, i): s[j] = False
    return [i for i in range(2, b) if s[i]]

PRIMES = [q for q in primes_upto(50000) if q not in (2, 3, 5, 7)]

def ord_of(a, q):
    d = q - 1; n = d; f = 2
    while f * f <= n:
        if n % f == 0:
            while n % f == 0: n //= f
            while d % f == 0 and pow(a, d // f, q) == 1: d //= f
        f += 1
    if n > 1:
        while d % n == 0 and pow(a, d // n, q) == 1: d //= n
    return d

ORD10, O3, O7 = {}, {}, {}
for q in PRIMES:
    ORD10[q] = ord_of(10, q); O3[q] = ord_of(3, q); O7[q] = ord_of(7, q)
PORDER = sorted(PRIMES, key=lambda q: (O3[q] * O7[q] // math.gcd(O3[q], O7[q])) / (q - 1))

class Ctx:
    def __init__(self, S, A, K=None):
        self.S = S; self.A = A
        self.K = 9 * S - 1 if K is None else K
        self.t0 = vp(self.K, 2)
        self.qmin = max(3, self.t0 + 1)
        self.nodes = []

def signature(c, rho, ML, kappa, MQ):
    K, A = c.K, c.A
    j = min(vp(ML, 3), vp(MQ, 3)); m3 = 3 ** (j + 2)
    X = (pow(10, rho, m3) + A * pow(10, kappa, m3) + K) % m3
    e3 = vp(X, 3) if X else j + 2
    a = (e3, e3) if e3 <= j + 1 else (j + 2, None)
    if ML % 6 or MQ % 6:
        w = (0, None)
    else:
        i = min(vp(ML, 7), vp(MQ, 7)); m7 = 7 ** (i + 1)
        Y = (pow(10, rho, m7) + A * pow(10, kappa, m7) + K) % m7
        e7 = vp(Y, 7) if Y else i + 1
        w = (e7, e7) if e7 <= i else (i + 1, None)
    return a, w

def could_o(p, T, sig, o3, o7):
    """one-sided: False => T not ≡ 3^a 7^w (mod p) for any a,w in ranges."""
    if T == 0:
        return False
    (a_lo, a_hi), (w_lo, w_hi) = sig
    x = T * pow(pow(3, a_lo, p), -1, p) % p
    x = x * pow(pow(7, w_lo, p), -1, p) % p
    if a_hi is None and w_hi is None:
        return pow(x, o3 * o7 // math.gcd(o3, o7), p) == 1
    if a_hi is None: return pow(x, o3, p) == 1
    if w_hi is None: return pow(x, o7, p) == 1
    return x == 1

def could(p, T, sig):
    return could_o(p, T, sig, O3[p], O7[p])

def ord_pp(a, p, k):
    # order of a mod p^k (p prime, p ∤ a), via lifting
    if k <= 0: return 1
    o = 1; x = a % p
    while x != 1:
        x = x * a % p; o += 1
    pk = p
    for _ in range(k - 1):
        pk *= p
        if pow(a, o, pk) != 1: o *= p
    return o

def pin_loose(c, sig, qp):
    """one-sided pin at 10^qp (valid for every class point with q >= qp):
    3^a 7^w ≡ K/2^t0 must hold mod 2^{qp-t0} and mod 5^{qp}; kill if unsolvable."""
    K2 = c.K // 2 ** c.t0
    for base, e in ((2, qp - c.t0), (5, qp)):
        if e < 1: continue
        m = base ** e
        x0 = K2 % m if base == 2 else K2 * pow(pow(2, c.t0, m), -1, m) % m
        if not could_o(m, x0, sig, ord_pp(3, base, e), ord_pp(7, base, e)):
            return True
    return False

def q_minimum(kappa, MQ, qlo):
    q = kappa % MQ
    while q < qlo: q += MQ
    return q

def closure_mod(gens, N):
    """subgroup of (Z/N)* generated by gens, as an explicit set (size-capped)."""
    S = {1 % N}
    frontier = [1 % N]
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = x * g % N
            if y not in S:
                if len(S) >= SET_CAP:
                    raise AssertionError("set cap")
                S.add(y); frontier.append(y)
    return S

def crt_lift(r, M, gg, d):
    """CRT: x ≡ r (mod M), x ≡ gg (mod d); assumes gg ≡ r (mod gcd(M,d)).
    Returns x mod lcm(M,d) = M*(d/g)."""
    g = math.gcd(M, d); b = d // g
    t = ((gg - r) // g) * pow(M // g, -1, b) % b
    return (r + M * t) % (M * b)

def pin_reachable(c, sig, qp):
    """C ≡ K/2^t0 (mod 2^{qp-t0} 5^{qp}); is 3^a 7^w ≡ C solvable for (a,w) in sig?"""
    N2 = 2 ** (qp - c.t0); N5 = 5 ** qp; N = N2 * N5
    K2 = c.K // 2 ** c.t0
    c2, c5 = K2 % N2, K2 * pow(pow(2, c.t0, N5), -1, N5) % N5
    C = (c2 + N2 * ((c5 - c2) * pow(N2, -1, N5) % N5)) % N
    (a_lo, a_hi), (w_lo, w_hi) = sig
    gens = []
    if a_hi is None: gens.append(3)
    if w_hi is None: gens.append(7)
    S = closure_mod(gens, N) if gens else {1}
    if a_hi is not None: S = {x * pow(3, a_hi, N) % N for x in S}
    if w_hi is not None: S = {x * pow(7, w_hi, N) % N for x in S}
    return C in S

def size_solutions(c, rho, ML, kappa, MQ, a0, w0):
    N0 = 2 ** c.t0 * 3 ** a0 * 7 ** w0
    R = N0 - c.K
    out = []
    if R > 0:
        p10 = 1
        q = 0
        while p10 <= R:
            if R % p10 == 0:
                u = R // p10 - c.A
                if u > 0:
                    e = vp(u, 10)
                    if 10 ** e == u and e >= 1:
                        L = q + e
                        if q >= c.qmin and L % ML == rho % ML and q % MQ == kappa % MQ:
                            if 10 ** L + c.A * 10 ** q + c.K == N0:
                                out.append([L, q])
            q += 1; p10 *= 10
    return out

def try_kill(c, rho, ML, kappa, MQ, sig):
    K, A, t0 = c.K, c.A, c.t0
    # 1. T0
    for p in PORDER[:KILL_SCAN]:
        d = ORD10[p]
        if ML % d == 0 and MQ % d == 0 and (pow(10, rho, p) + A * pow(10, kappa, p) + K) % p == 0:
            return ("T0", p)
    # 2. pin kills.  (a) exact coset-set test at the domain floor 10^qmin;
    # (b) one-sided test at 10^{q'}, q' = min(class q-minimum, 40) — valid because
    # every class point has q >= that minimum and the pin holds mod 10^{q'} for q' <= q.
    try:
        if not pin_reachable(c, sig, c.qmin):
            return ("pin", [c.qmin, 1])
    except AssertionError:
        pass  # L2b patch: coset set too large to decide -> treat as reachable (sound)
    qp = min(q_minimum(kappa, MQ, c.qmin), 40)
    if pin_loose(c, sig, qp):
        return ("pin", [qp, 0])
    # 3. region tests at aux primes (over all aligned lifts when d does not divide M)
    for p in PORDER[:KILL_SCAN]:
        d = ORD10[p]
        gL = math.gcd(ML, d); gQ = math.gcd(MQ, d)
        nL, nQ = d // gL, d // gQ
        if nL * nQ > COMBO_CAP:
            continue
        inv2 = pow(pow(2, t0, p), -1, p)
        alive = False
        for ggL in range(rho % gL, d, gL):
            cL = crt_lift(rho, ML, ggL, d)
            pLL = pow(10, ggL, p)
            for ggQ in range(kappa % gQ, d, gQ):
                cQ = crt_lift(kappa, MQ, ggQ, d)
                T = (pLL + A * pow(10, ggQ, p) + K) * inv2 % p
                sg = signature(c, cL, ML * nL, cQ, MQ * nQ) if nL * nQ > 1 else sig
                if could(p, T, sg):
                    alive = True; break
            if alive: break
        if not alive:
            return ("prime", p)
    return None

def best_split(c, rho, ML, kappa, MQ):
    best = None
    for p in PORDER[:SPLIT_SCAN]:
        d = ORD10[p]
        gL = math.gcd(ML, d); gQ = math.gcd(MQ, d)
        nL, nQ = d // gL, d // gQ
        nc = nL * nQ
        if nc < 2 or nc > SPLIT_CAP or max(ML * nL, MQ * nQ) > MAXM:
            continue
        inv2 = pow(pow(2, c.t0, p), -1, p)
        killed = 0
        for s in range(nL):
            cL = (rho + s * ML) % (ML * nL)
            for t in range(nQ):
                cQ = (kappa + t * MQ) % (MQ * nQ)
                sg = signature(c, cL, ML * nL, cQ, MQ * nQ)
                T = (pow(10, cL, p) + c.A * pow(10, cQ, p) + c.K) * inv2 % p
                if not could(p, T, sg):
                    killed += 1
        if killed == 0: continue
        surv = nc - killed
        key = (surv, -killed)
        if best is None or key < best[0]:
            best = (key, p, nL, nQ)
    return best

def run(S, A, K=None):
    c = Ctx(S, A, K)
    nodes = c.nodes
    def emit(d):
        nodes.append(d)
        return len(nodes) - 1

    def process(rho, ML, kappa, MQ, parent, depth=0):
        assert len(nodes) < NODE_CAP, "node cap"
        assert depth < 200, "depth"
        sig = signature(c, rho, ML, kappa, MQ)
        (a_lo, a_hi), (w_lo, w_hi) = sig
        if a_hi is not None and w_hi is not None:
            d = {"k": "l", "p": parent, "r": [rho, kappa], "m": [ML, MQ],
                 "a": [a_lo, a_hi], "w": [w_lo, w_hi],
                 "x": {"sz": [a_lo, w_lo], "L": size_solutions(c, rho, ML, kappa, MQ, a_lo, w_lo)}}
            return emit(d)
        kill = try_kill(c, rho, ML, kappa, MQ, sig)
        if kill:
            kind, p = kill
            d = {"k": "l", "p": parent, "r": [rho, kappa], "m": [ML, MQ],
                 "a": [a_lo, a_hi], "w": [w_lo, w_hi], "x": {kind: p}}
            return emit(d)
        bs = best_split(c, rho, ML, kappa, MQ)
        use = False
        if bs is not None:
            (surv, _k), p, nL, nQ = bs
            if surv <= 6 or surv <= 0.25 * nL * nQ:
                use = True
        if use:
            (_, p, nL, nQ) = bs
            nML, nMQ = ML * nL, MQ * nQ
            survivors = []
            for s in range(nL):
                cL = (rho + s * ML) % nML
                for t in range(nQ):
                    cQ = (kappa + t * MQ) % nMQ
                    sg = signature(c, cL, nML, cQ, nMQ)
                    T = (pow(10, cL, p) + c.A * pow(10, cQ, p) + c.K) * pow(pow(2, c.t0, p), -1, p) % p
                    if could(p, T, sg):
                        survivors.append((cL, cQ))
            if survivors:  # L2b patch: if no child survives, fall through to deepen
                nd = {"k": "i", "p": parent, "r": [rho, kappa], "m": [ML, MQ], "c": [], "rest": None}
                nid = emit(nd)
                for (cL, cQ) in survivors:
                    nd["c"].append(process(cL, nML, cQ, nMQ, nid, depth + 1))
                if len(survivors) < nL * nQ:
                    nd["rest"] = {"q": p}
                return nid
        # deepen: raise the 3- or 7-valuation of the coordinate with smaller valuation
        ua = a_hi is None; uw = w_hi is None
        if ua and (not uw or min(vp(ML, 3), vp(MQ, 3)) <= min(vp(ML, 7), vp(MQ, 7))):
            mult, which = 3, ("L" if vp(ML, 3) <= vp(MQ, 3) else "Q")
        elif uw:
            mult, which = 7, ("L" if vp(ML, 7) <= vp(MQ, 7) else "Q")
        else:
            mult, which = 3, "L"
        if which == "L":
            nML = ML * mult
            assert nML <= MAXM
            nd = {"k": "i", "p": parent, "r": [rho, kappa], "m": [ML, MQ], "c": [], "rest": None}
            nid = emit(nd)
            for s in range(mult):
                nd["c"].append(process((rho + s * ML) % nML, nML, kappa, MQ, nid, depth + 1))
        else:
            nMQ = MQ * mult
            assert nMQ <= MAXM
            nd = {"k": "i", "p": parent, "r": [rho, kappa], "m": [ML, MQ], "c": [], "rest": None}
            nid = emit(nd)
            for s in range(mult):
                nd["c"].append(process(rho, ML, (kappa + s * MQ) % nMQ, nMQ, nid, depth + 1))
        return nid

    sys.setrecursionlimit(50000)
    root = {"k": "i", "p": -1, "r": [0, 0], "m": [1, 1], "c": [], "rest": None}
    rid = emit(root)
    for r in range(6):
        for k in range(6):
            root["c"].append(process(r, 6, k, 6, rid))

    n_leaves = sum(1 for d in nodes if d["k"] == "l")
    n_rest = sum(1 for d in nodes if d["k"] == "i" and d.get("rest"))
    sols = sorted({tuple(Lq) for d in nodes if d["k"] == "l" and "sz" in d["x"] for Lq in d["x"]["L"]})
    path = f"cert2d_S{S}_A{A}.jsonl" if K is None else f"cert2d_K{K}_A{A}.jsonl"
    with open(path, "w") as f:
        f.write(json.dumps({"k": "meta", "A": A, "K": c.K, "qmin": c.qmin}) + "\n")
        for d in nodes:
            f.write(json.dumps(d) + "\n")
    print(f"S={S} A={A} K={c.K} qmin={c.qmin}: nodes={len(nodes)} leaves={n_leaves} rest={n_rest} "
          f"solutions={sols} bytes={os.path.getsize(path)}", flush=True)

PAIRS = [(1, 9), (10, 9), (1, 18), (10, 18), (1, 27), (10, 27), (30, 27), (11, 9), (101, 9), (110, 9)]
if __name__ == "__main__":
    args = sys.argv[1:]
    if args and args[0] == "K":          # explicit (A, K): gen_cert2d.py K A K
        run(None, int(args[1]), int(args[2]))
    else:
        todo = [tuple(map(int, args))] if args else PAIRS
        for S, A in todo:
            run(S, A)
    print("ALL DONE")
