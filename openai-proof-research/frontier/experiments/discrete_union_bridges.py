#!/usr/bin/env python3
"""Finite checks of the discrete scout's obstructions; no conjecture proof."""
from fractions import Fraction as F
from itertools import product
from math import log, log2
import json

c = log(3/4)/log(1/2)
checks = []
for n in range(1, 5):
    N = 1 << n
    count = rare = 0
    for table in range(1 << N):
        g = [(table >> x) & 1 for x in range(N)]
        if any(g[x] > g[x | (1 << i)] for x in range(N) for i in range(n)):
            continue
        count += 1
        p = F(sum(g), N)
        q = F(sum(g[x] * 3**x.bit_count() for x in range(N)), 4**n)
        defect = q - (2*p-p*p)
        direct = F(sum(g[x|y] != (g[x] | g[y]) for x in range(N) for y in range(N)), N*N)
        assert defect == direct
        assert float(q) + 1e-12 >= float(p)**c
        if 0 < p < F(1,2):
            rare += 1
            assert defect > 0
        # Exact join-homomorphism: constant one, constant zero, or OR of coordinates.
        if defect == 0:
            assert all(g[x] == (g[0] or any(g[1 << i] for i in range(n) if x & (1 << i))) for x in range(N))
    checks.append({'dimension':n,'monotone_functions':count,'rare_nonzero_functions':rare})

# Exact equal-fiber rigidity for all base sets and up to four generators on [3].
balanced_count = total = 0
for m in range(5):
    for B in range(8):
        choices = [a for a in range(8) if a | B == a]
        for gens in product(choices, repeat=m):
            total += 1
            fibers = {}
            for x in range(1 << m):
                image = B
                for i,a in enumerate(gens):
                    if x & (1 << i): image |= a
                fibers[image] = fibers.get(image,0)+1
            balanced = len(set(fibers.values())) == 1
            effective = [i for i,a in enumerate(gens) if a != B]
            private = True
            for i in effective:
                others = B
                for j in effective:
                    if j != i: others |= gens[j]
                private &= bool(gens[i] & ~others)
            assert balanced == private
            balanced_count += balanced

and_rows=[]
for k in range(1,11):
    p=F(1,2**k)
    defect=F(3,4)**k-2*p+p*p
    assert abs(float(defect) - (float(p)**c-2*float(p)+float(p*p))) < 1e-12
    and_rows.append({'k':k,'p':str(p),'union_defect':str(defect)})

# Chain example: generated by {1}, {1,2}, {1,2,3}.
chain_fibers={}
for x in range(8):
    z=0
    for i,a in enumerate([1,3,7]):
        if x & (1<<i):z|=a
    chain_fibers[z]=chain_fibers.get(z,0)+1
assert chain_fibers == {0:1,1:1,3:2,7:4}

# Full-support Eulerian independent blowup obstruction.
edges={(0,1),(1,2),(2,3),(3,4),(4,0),(0,2)}
assert not any((a,b) in edges and (b,d) in edges and (d,a) in edges for a,b,d in product(range(5),repeat=3))
# Balance rows 2+3+4: (m3-m1-m0)+(m4-m2)+(m0-m3)=m4-m2-m1;
# subtract row 3 (m4-m2) gives -m1; equivalently row2+row4=-m1.
rows=[]
for v in range(5):
    rows.append([int((v,u) in edges)-int((u,v) in edges) for u in range(5)])
assert [rows[2][u]+rows[4][u] for u in range(5)] == [0,-1,0,0,0]

result={'monotone_checks':checks,'equal_fiber_generator_systems':total,'balanced_systems':balanced_count,'AND_obstruction':and_rows,'chain_fibers':chain_fibers,'Eulerian_balance_rows':rows,'status':'all finite checks passed; real-exponent comparisons are floating-point sanity checks only'}
print(json.dumps(result,indent=2))
