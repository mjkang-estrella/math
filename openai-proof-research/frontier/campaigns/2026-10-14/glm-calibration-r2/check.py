def run_battery(N, Cks):
    CERT_DATA.clear()
    results = {}
    for cid, fn in CHECKS:
        t0 = time.time()
        err = None
        try:
            ok, detail = fn(N, Cks)
        except Exception as exc:  # a crash is a failure, recorded honestly
            ok, detail, err = False, "exception: %r" % (exc,), repr(exc)
        entry = {
            "status": "PASS" if ok else "FAIL",
            "failed_by": None if (ok or err) else "comparison_mismatch",
            "detail": detail,
            "seconds": round(time.time() - t0, 3),
        }
        if err:
            entry["error"] = err
            entry["failed_by"] = "exception"
        if cid in CERT_DATA:
            entry["data"] = CERT_DATA[cid]
        results[cid] = entry
    return results


def _sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


