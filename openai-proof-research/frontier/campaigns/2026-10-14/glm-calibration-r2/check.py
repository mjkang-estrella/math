def cert_Pencil_theta(N, Cks):
    """charpoly of Re(e^{-i theta} N) is theta-independent and equals
    (t^2-1)^2 (t^2 - 7/64); verified symbolically in c=cos, s=sin reduced
    modulo c^2 + s^2 - 1."""
    c, s = symbols('c s')
    A = sp.MutableDenseMatrix(6, 6, lambda i, j: expand0(
        ((c - I * s) * N[i, j] + (c + I * s) * N.conjugate().T[i, j]) / 2))
    cp = sp.Poly(A.charpoly(T).as_expr(), T)
    G = sp.groebner([c ** 2 + s ** 2 - 1], c, s, order='lex',
                    domain=sp.QQ.frac_field(s2, s7))
    coeffs = {}
    for (deg,), coef in cp.terms():
        _, rmd = G.reduce(sp.Poly(sp.expand(coef), c, s))
        coeffs[deg] = sp.expand(rmd.as_expr())
    expected = sp.expand((T ** 2 - 1) ** 2 * (T ** 2 - R(7, 64)))
    exp_coeffs = {d: sp.expand(sp.Poly(expected, T).coeff_monomial(T ** d))
                  for d in range(7)}
    exp_coeffs = {d: v for d, v in exp_coeffs.items() if v != 0}
    ok = coeffs == exp_coeffs
    return ok, ("charpoly Re(e^{-i theta} N), reduced mod c^2+s^2=1, is "
                "theta-independent and equals (t^2-1)^2 (t^2-7/64): every "
                "support pencil has eigenvalues 1,1,-1,-1,sqrt(7)/8,-sqrt(7)/8"
                if ok else "reduced charpoly coefficients %s" % coeffs)


