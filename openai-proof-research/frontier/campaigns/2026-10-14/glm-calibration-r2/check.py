def build_PN(N, Cks):
    """Base-first P[N] = sum_k N^k (x) C_k on E(6) (x) F(2).

    Convention under test: index 2*i + j, i.e.
    P[N][2*i+j, 2*i'+j'] = sum_k (N^k)_{i,i'} (C_k)_{j,j'}.
    """
    PN = sp.MutableDenseMatrix(12, 12, lambda i, j: 0)
    Nk = sp.eye(6)
    for k in range(4):
        if k > 0:
            Nk = Nk * N
        for i in range(6):
            for ip in range(6):
                v = Nk[i, ip]
                if v != 0:
                    for j in range(2):
                        for jp in range(2):
                            w = Cks[k][j, jp]
                            if w != 0:
                                PN[2 * i + j, 2 * ip + jp] = \
                                    PN[2 * i + j, 2 * ip + jp] + v * w
    return PN


def build_PN_fiberfirst(N, Cks):
    """REPAIRED (D1): the genuine fiber-first convention
    sum_k C_k (x) N^k on C^2 (x) C^6, with the correct six-dimensional
    stride: index 6*j + i, i.e. P[N][6*j+i, 6*jp+ip] =
    sum_k (C_k)_{j,jp} (N^k)_{i,ip}.  The original copy used stride 2 and
    produced a malformed matrix (its last four rows/columns unused).
    """
    PF = sp.MutableDenseMatrix(12, 12, lambda i, j: 0)
    Nk = sp.eye(6)
    for k in range(4):
        if k > 0:
            Nk = Nk * N
        for j in range(2):
            for jp in range(2):
                w = Cks[k][j, jp]
                if w != 0:
                    for i in range(6):
                        for ip in range(6):
                            v = Nk[i, ip]
                            if v != 0:
                                PF[6 * j + i, 6 * jp + ip] = \
                                    PF[6 * j + i, 6 * jp + ip] + w * v
    return PF


def build_flip_J():
    """The basis-flip permutation J mapping base-first coordinates (2i+j) to
    fiber-first coordinates (6j+i): J[6*j+i, 2*i+j] = 1.  J is a real
    permutation matrix, so J* = J.T.  With P = P[N] base-first and F the
    true fiber-first assembly, F = J P J* exactly.
    """
    J = sp.zeros(12, 12)
    for i in range(6):
        for j in range(2):
            J[6 * j + i, 2 * i + j] = 1
    return J


