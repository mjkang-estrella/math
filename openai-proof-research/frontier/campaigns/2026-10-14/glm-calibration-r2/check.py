def words_upto(N, L):
    """All words of length <= L in {N, N*} (0 = identity) for the ACTUAL
    matrix argument N, as a flat list.  No cache: every call rebuilds from
    the passed N, so a mutated N can never silently reuse baseline words.
    """
    mats = [sp.eye(6)]
    cur = [sp.eye(6)]
    for _ in range(L):
        nxt = [W * N for W in cur] + [W * N.conjugate().T for W in cur]
        mats += nxt
        cur = nxt
    return mats


def cyclic_profile(N):
    """Cyclicity and star-algebra data for the ACTUAL N passed in.

    Returns (ranks, minL, dim6): the rank of {W e1 : |W| <= L} for
    L = 0..5, the minimal such L reaching 6 (None if never), and the
    word-space dimension of the unital *-algebra at word length <= 6.
    Cyclicity (minL) and the full-algebra dimension (dim6) are different
    claims (e1 cyclic vs algebra = M_6(C)) and are reported separately.
    """
    e1 = sp.eye(6)[:, 0]
    ranks = {}
    minL = None
    for L in range(0, 6):
        Ws = words_upto(N, L)
        Mx = sp.Matrix.hstack(*[W * e1 for W in Ws])
        ranks[L] = Mx.rank()
        if ranks[L] == 6 and minL is None:
            minL = L
    Ws6 = words_upto(N, 6)
    Mv = sp.Matrix.hstack(*[sp.Matrix(list(W)).reshape(36, 1) for W in Ws6])
    dim6 = Mv.rank()
    return ranks, minL, dim6


