def cert_BBstar(N, Cks):
    PN = build_PN(N, Cks)
    B = sp.Matrix(3, 3, lambda i, j: PN[B_OUTS[i], B_INS[j]])
    BBs = B.conjugate().T * B
    u = sp.Matrix([1, 0, 1]) / sqrt(2)
    ok = exact_eq(BBs * u, 4 * u)
    w1 = sp.Matrix([1, 0, -1]) / sqrt(2)
    w2 = sp.Matrix([0, 1, 0])
    comp = sp.Matrix([[expand0((w1.T * BBs * w1)[0, 0]),
                       expand0((w1.T * BBs * w2)[0, 0])],
                      [expand0((w2.T * BBs * w1)[0, 0]),
                       expand0((w2.T * BBs * w2)[0, 0])]])
    ok = ok and exact_eq(comp, COMPLEMENTARY_2X2)
    tr = expand0(comp.trace())
    dt = expand0(comp.det())
    ok = ok and tr == R(569, 256) and dt == R(49, 64)
    # complementary eigenvalues and ordering, decided on integer squares
    lam_p = (R(569, 512) + 33 * sqrt(113) / 512)
    evs_ok = sp.simplify(sp.expand(
        (T - 4) * (T ** 2 - R(569, 256) * T + R(49, 64)) -
        sp.expand((T - 4) * (T - lam_p) * (T - (R(569, 512) - 33 * sqrt(113) / 512)))
    )) == 0
    order_ok = (33 ** 2 * 113 < 779 ** 2)  # (569+33sqrt113)/512 < 337/128
    ok = ok and evs_ok and order_ok
    return ok, ("B*B (1,0,1)/sqrt2 = 4 (1,0,1)/sqrt2; on the orthogonal "
                "complement B*B = [[67/64, 33sqrt7/128],[33sqrt7/128, "
                "301/256]]; complementary trace 569/256, det 49/64; "
                "eigenvalues 4, (569+-33sqrt113)/512; the latter two lie "
                "below 337/128 since 33^2*113 = %d < %d = 779^2"
                % (33 ** 2 * 113, 779 ** 2)
                if ok else "B*B structure check failed (trace=%s, det=%s)"
                % (tr, dt))


