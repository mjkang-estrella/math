def cert_Control_reducible(N, Cks):
    """D2 companion control: a reducible NONZERO matrix must not produce
    full ranks.  N_red has entries (0,1)=1 and (2,3)=2 and zeros elsewhere
    (nilpotent chains on index blocks {0,1} and {2,3}).  The orthogonal
    projection P = diag(1,1,1,1,0,0) is constant on those blocks and
    commutes with N_red and N_red* exactly (verified below), so N_red is
    reducible; a priori then the cyclic span of e1 has dimension <= 2 (the
    span of {e1, e2} is invariant, verified exactly below) and the unital
    *-algebra has dimension < 36 (it lies in the commutant of P, of
    dimension 4^2 + 2^2 = 20).  The measured values must respect these
    bounds.
    """
    Nred = sp.zeros(6, 6)
    Nred[0, 1] = 1
    Nred[2, 3] = 2
    P = sp.diag(1, 1, 1, 1, 0, 0)
    comm_N = exact_eq(P * Nred, Nred * P)
    comm_Nst = exact_eq(P * Nred.conjugate().T, Nred.conjugate().T * P)
    # exact invariance of span{e1, e2} under N_red and N_red*
    S = sp.eye(6)[:, :2]
    E12 = sp.Matrix([[0, 1], [0, 0]])
    E21 = sp.Matrix([[0, 0], [1, 0]])
    inv_N = exact_eq(Nred * S, S * E12) and \
        exact_eq(Nred.conjugate().T * S, S * E21)
    ranks, minL, dim6 = cyclic_profile(Nred)
    ok = comm_N and comm_Nst and inv_N and \
        max(ranks.values()) <= 2 and minL is None and dim6 < 36
    CERT_DATA["Control_reducible"] = {
        "commuting_projection_diagonal": [str(z) for z in P.diagonal()],
        "projection_commutes_with_N_and_Nstar": bool(comm_N and comm_Nst),
        "span_e1_e2_invariant_verified": bool(inv_N),
        "cyclic_ranks_by_word_length": {str(k): int(v) for k, v in
                                        ranks.items()},
        "unital_algebra_dimension": int(dim6),
        "a_priori_bounds": {"cyclic_dim": "<= 2 (invariant span{e1,e2})",
                            "algebra_dim": "< 36 (commutant of P has dim "
                                           "4^2 + 2^2 = 20)"},
    }
    return ok, ("reducible control: diag(1,1,1,1,0,0) commutes with N_red "
                "and N_red*; cyclic ranks %s never reach 6 (a priori <= 2), "
                "unital *-algebra dimension %s < 36 (a priori < 36)"
                % (ranks, dim6) if ok else
                "reducible control FAILED: comm=%s/%s inv=%s ranks=%s "
                "dim6=%s" % (comm_N, comm_Nst, inv_N, ranks, dim6))


def cert_Irreducibility_rationalized(N, Cks):
    """Independent irreducibility certificate via exact rationalization.

    D = diag(1,1,1,sqrt(14),sqrt(14),sqrt(7)) conjugates N and N* to
    rational matrices A = D^-1 N D, B = D^-1 N* D (simultaneous similarity).
    The word-space dimensions of the unital *-algebra of (A,B) through word
    lengths 0..6 are computed over Q, and at length 6 an EXPLICIT basis of
    36 words is extracted (rref pivot columns) and its 36x36 flattened
    determinant verified nonzero.  Similarity transfers the span statement
    back to (N, N*), so the *-algebra generated by N is all of M_6(C), and
    any orthogonal projection commuting with N and N* is 0 or I: unitary
    irreducibility, finitely verified.  This path is independent of
    cert_Cyclic_rank's radical-field rank computation (the review's
    audit.py method, reproduced here on the actual N argument).
    """
    D = sp.diag(1, 1, 1, s14, s14, s7)
    A = D.inv() * N * D
    B = D.inv() * N.conjugate().T * D
    ok_rat = all(z.is_Rational for z in A) and all(z.is_Rational for z in B)
    words = [('identity', sp.eye(6))]
    cur = [('identity', sp.eye(6))]
    dims = []
    basis_words = None
    det = None
    for length in range(0, 7):
        if length:
            cur = ([(w + 'N', v * A) for w, v in cur] +
                   [(w + 'S', v * B) for w, v in cur])
            words += cur
        V = sp.Matrix.hstack(*[sp.Matrix(list(v)).reshape(36, 1)
                               for w, v in words])
        dims.append(V.rank())
        if length == 6:
            _, piv = V.rref()
            basis = V[:, list(piv)]
            det = sp.factor(basis.det(method='domain-ge'))
            basis_words = ['identity' if not words[i][0] else words[i][0]
                           for i in piv]
    ok = ok_rat and dims[6] == 36 and det != 0
    CERT_DATA["Irreducibility_rationalized"] = {
        "similarity_D_diagonal": [str(z) for z in D.diagonal()],
        "rationalized": bool(ok_rat),
        "word_space_dimensions_lengths_0_through_6": dims,
        "basis_word_convention": ("Words multiply left-to-right; N=A, S=B; "
                                  "original matrices are simultaneously "
                                  "similar by D."),
        "basis_words": basis_words,
        "nonzero_36x36_basis_determinant": str(det),
    }
    return ok, ("rationalized *-algebra of (N, N*) has word-space dimensions "
                "%s through length 6, with an explicit 36-word basis of "
                "nonzero determinant %s: the *-algebra is all of M_6(C), so "
                "any orthogonal projection commuting with N and N* is 0 or I"
                % (dims, det) if ok else
                "rationalized irreducibility FAILED: rational=%s dims=%s "
                "det=%s" % (ok_rat, dims, det))


