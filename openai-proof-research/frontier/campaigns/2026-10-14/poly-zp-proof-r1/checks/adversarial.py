"""Independent adversarial finite diagnostics for the poly-Z_p proof review.

Writes nothing; the JSON report goes to stdout only. Standard library only.
Shares no code with the candidate's checks.py. Subgroups of finite p-groups
are enumerated by maximal-subgroup descent through Frattini quotients, not
by the candidate's generator-extension search.

Finite/profinite bridge (argued in review.md, Section 4): every test group is
a quotient E/M of a profinite group E, where M is a closed normal subgroup
generated by p^B-th powers. A coset action of degree p^h of a pro-p group has
p-group image in Sym(p^h), whose elements have order <= p^h, so for h <= B the
open subgroups of index p^h of E correspond bijectively to the subgroups of
index p^h of E/M. Every assertion below about E is restricted to that range.
Finite checks are evidence about the stated examples only, never a proof.
"""
from fractions import Fraction
from itertools import product
import json
import sys

sys.dont_write_bytecode = True


# ---------------------------------------------------------------- groups
class Grp:
    def __init__(self, elements, mul):
        self.el = list(elements)
        self.n = len(self.el)
        ix = {x: i for i, x in enumerate(self.el)}
        self.t = [[ix[mul(x, y)] for y in self.el] for x in self.el]
        self.e = next(i for i in range(self.n)
                      if all(self.t[i][j] == j for j in range(self.n)))
        self.inv = [0] * self.n
        for i in range(self.n):
            row = self.t[i]
            self.inv[i] = row.index(self.e)

    def closure(self, gens, base=None):
        S = set(base) if base else {self.e}
        frontier = list(S)
        while frontier:
            new = []
            for x in frontier:
                row = self.t[x]
                for g in gens:
                    y = row[g]
                    if y not in S:
                        S.add(y)
                        new.append(y)
            frontier = new
        return frozenset(S)

    def power(self, x, k):
        r = self.e
        for _ in range(k):
            r = self.t[r][x]
        return r

    def comm(self, x, y):
        t, inv = self.t, self.inv
        return t[t[t[inv[x]][inv[y]]][x]][y]

    def conj(self, g, x):  # g x g^-1
        return self.t[self.t[g][x]][self.inv[g]]


def generators(G, K):
    gens, S = [], frozenset([G.e])
    for x in sorted(K):
        if x not in S:
            gens.append(x)
            S = G.closure(gens)
            if len(S) == len(K):
                break
    return gens


def frattini_data(G, K, p):
    """Return (Phi(K), basis lifts, coordinate map K -> F_p^d)."""
    gens = generators(G, K)
    seeds = [G.power(s, p) for s in gens]
    seeds += [G.comm(s, t) for s in gens for t in gens]
    Phi = G.closure(seeds)
    while True:  # normal closure in K
        extra = [G.conj(g, x) for g in gens for x in Phi]
        if all(y in Phi for y in extra):
            break
        Phi = G.closure(list(Phi) + extra)
    basis, S = [], Phi
    for x in sorted(K):
        if x not in S:
            basis.append(x)
            S = G.closure(basis, base=Phi)
    d = len(basis)
    assert len(K) == len(Phi) * p ** d
    coord = {}
    for v in product(range(p), repeat=d):
        r = G.e
        for b, k in zip(basis, v):
            r = G.t[r][G.power(b, k)]
        for f in Phi:
            coord[G.t[r][f]] = v
    assert len(coord) == len(K)
    return Phi, basis, coord


def maximal_subgroups(G, K, p):
    if len(K) == 1:
        return []
    _, basis, coord = frattini_data(G, K, p)
    d = len(basis)
    out = []
    for f in product(range(p), repeat=d):
        nz = [c for c in f if c]
        if not nz or nz[0] != 1:
            continue
        out.append(frozenset(x for x in K
                             if sum(a * b for a, b in zip(f, coord[x])) % p == 0))
    return out


def descent(G, top, p, depth):
    """levels[h] = set of subgroups of index p^h in `top`, for h <= depth."""
    levels = [{frozenset(top)}]
    for _ in range(depth):
        nxt = set()
        for K in levels[-1]:
            nxt.update(maximal_subgroups(G, K, p))
        levels.append(nxt)
    return levels


# ------------------------------------------------- constructions/automorphisms
def extend_hom(N, gens, images):
    """Permutation of N extending gens -> images, or None if ill-defined."""
    phi = {N.e: N.e}
    frontier = [N.e]
    while frontier:
        new = []
        for x in frontier:
            for g, im in zip(gens, images):
                y, iy = N.t[x][g], N.t[phi[x]][im]
                if y in phi:
                    if phi[y] != iy:
                        return None
                else:
                    phi[y] = iy
                    new.append(y)
        frontier = new
    if len(phi) != N.n or len(set(phi.values())) != N.n:
        return None
    return tuple(phi[i] for i in range(N.n))


def perm_order(a):
    k, cur, ident = 1, a, tuple(range(len(a)))
    while cur != ident:
        cur = tuple(a[x] for x in cur)
        k += 1
    return k


def compose_power(a, k):
    cur = tuple(range(len(a)))
    for _ in range(k):
        cur = tuple(a[x] for x in cur)
    return cur


def semidirect(N, alpha, Lq, p):
    q = p ** Lq
    pw = [tuple(range(N.n))]
    for _ in range(1, q):
        pw.append(tuple(alpha[x] for x in pw[-1]))
    assert tuple(alpha[x] for x in pw[-1]) == pw[0], 'alpha^(p^L) != id'
    return Grp(list(product(range(N.n), range(q))),
               lambda x, y: (N.t[x[0]][pw[x[1]][y[0]]], (x[1] + y[1]) % q))


def zmod_tuple_group(moduli):
    return Grp(list(product(*[range(m) for m in moduli])),
               lambda x, y: tuple((a + b) % m for a, b, m in zip(x, y, moduli)))


def heis(q, qz=None):
    """Heisenberg quotient: x,y mod q and central z mod qz (qz | q)."""
    qz = qz or q
    return Grp(list(product(range(q), range(q), range(qz))),
               lambda x, y: ((x[0] + y[0]) % q, (x[1] + y[1]) % q,
                             (x[2] + y[2] + x[0] * y[1]) % qz))


def dihedral(m):
    return Grp(list(product(range(m), range(2))),
               lambda x, y: ((x[0] + (-1) ** x[1] * y[0]) % m, (x[1] + y[1]) % 2))


def metacyclic(m, k, r):
    # C_m semidirect C_k, generator of C_k acting by multiplication by r
    return Grp(list(product(range(m), range(k))),
               lambda x, y: ((x[0] + pow(r, x[1], m) * y[0]) % m, (x[1] + y[1]) % k))


def quaternion8():
    # (sign, unit) with units 1,i,j,k encoded 0..3
    tab = {(0, 0): (1, 0), (0, 1): (1, 1), (0, 2): (1, 2), (0, 3): (1, 3),
           (1, 0): (1, 1), (1, 1): (-1, 0), (1, 2): (1, 3), (1, 3): (-1, 2),
           (2, 0): (1, 2), (2, 1): (-1, 3), (2, 2): (-1, 0), (2, 3): (1, 1),
           (3, 0): (1, 3), (3, 1): (1, 2), (3, 2): (-1, 1), (3, 3): (-1, 0)}

    def mul(x, y):
        s, u = tab[(x[1], y[1])]
        return (x[0] * y[0] * s, u)
    return Grp(list(product([1, -1], range(4))), mul)


def matrix_action(N, moduli, A, q):
    ix = {x: i for i, x in enumerate(N.el)}
    k = len(moduli)
    return tuple(ix[tuple(sum(A[r][c] * x[c] for c in range(k)) % q
                          for r in range(k))] for x in N.el)


def pgroup_automorphisms(N, p):
    _, basis, _ = frattini_data(N, frozenset(range(N.n)), p)
    autos = set()
    for images in product(range(N.n), repeat=len(basis)):
        a = extend_hom(N, basis, images)
        if a is not None:
            o = perm_order(a)
            while o % p == 0:
                o //= p
            if o == 1:
                autos.add(a)
    return sorted(autos)


# ------------------------------------------------------ Lemma 1 machinery
def vp(x, p):
    if x == 0:
        return 10 ** 9
    x, v = Fraction(x), 0
    num, den = x.numerator, x.denominator
    while num % p == 0:
        num //= p
        v += 1
    while den % p == 0:
        den //= p
        v -= 1
    return v


def c_t(p, t):
    c = Fraction(1)
    for i in range(1, t):
        c /= (1 - p ** i)
    return c


def A_ht(p, t, h):
    a = [1] + [0] * h
    for i in range(t - 1):
        for j in range(1, h + 1):
            a[j] += p ** (i + 1) * a[j - 1]
    # multiply by 1/(1-z)
    return sum(a[:h + 1])


def kernel_classes(N, alpha, p, depth):
    """N-conjugacy classes of subgroups by index level, with alpha action."""
    lv = descent(N, range(N.n), p, depth)
    gens = generators(N, frozenset(range(N.n)))
    data = []
    for b, subs in enumerate(lv):
        seen, classes = set(), []
        for V in sorted(subs, key=lambda s: sorted(s)):
            if V in seen:
                continue
            orb, todo = {V}, [V]
            while todo:
                W = todo.pop()
                for g in gens:
                    X = frozenset(N.conj(g, x) for x in W)
                    if X not in orb:
                        orb.add(X)
                        todo.append(X)
            seen |= orb
            classes.append(frozenset(orb))
        where = {V: i for i, cl in enumerate(classes) for V in cl}
        perm = [where[frozenset(alpha[x] for x in next(iter(cl)))] for cl in classes]
        data.append({'classes': classes, 'perm': perm, 'subs': subs})
    return data


def fixed_classes(perm, k):
    cur = list(range(len(perm)))
    for _ in range(k):
        cur = [perm[c] for c in cur]
    return sum(cur[i] == i for i in range(len(perm)))


def formula2(kc, p, h, shift=0):
    return sum(p ** b * fixed_classes(kc[b]['perm'], p ** (h - b + shift))
               for b in range(h + 1))


def parametrization_check(N, alpha, Lq, p, G, levels, kc, depth):
    """For each open H: projection p^a, V=H cap N, fiber over T^(p^a) is one
    right V-coset Vg with g alpha^(p^a)(V) g^-1 = V; map H -> (V,Vg) injective;
    image count equals sum over V of [N_N(V):V]."""
    q = p ** Lq
    checked = 0
    for h in range(depth + 1):
        keys = set()
        for H in levels[h]:
            pairs = [G.el[x] for x in H]
            proj = {s for _, s in pairs}
            a = min((vp(s, p) for s in proj if s), default=Lq)
            step = p ** a % q
            assert proj == {(step * k) % q for k in range(q)}
            V = frozenset(n for n, s in pairs if s == 0)
            fiber = frozenset(n for n, s in pairs if s == step)
            g = min(fiber)
            assert fiber == frozenset(N.t[v][g] for v in V)
            ap = compose_power(alpha, p ** a)
            img = frozenset(N.conj(g, ap[v]) for v in V)
            assert img == V
            assert len(H) * p ** h == G.n
            keys.add((a, V, fiber))
            checked += 1
        assert len(keys) == len(levels[h])
        # count all admissible (a, V, coset) directly from kernel data
        total = 0
        for a in range(h + 1):
            b = h - a
            if b >= len(kc):
                continue
            ap = compose_power(alpha, p ** a)
            for V in kc[b]['subs']:
                sols = [g for g in range(N.n)
                        if frozenset(N.conj(g, ap[v]) for v in V) == V]
                assert len(sols) % len(V) == 0
                total += len(sols) // len(V)
        assert total == len(levels[h])
    return checked


def lemma1_case(name, N, alpha, p, Lq, depth, mutations, bridge_note):
    assert depth <= Lq
    G = semidirect(N, alpha, Lq, p)
    D = semidirect(N, tuple(range(N.n)), Lq, p)
    lg = descent(G, range(G.n), p, depth)
    ld = descent(D, range(D.n), p, depth)
    kc = kernel_classes(N, alpha, p, depth)
    rows = []
    orbit_checks = 0
    for h in range(depth + 1):
        aG, aD = len(lg[h]), len(ld[h])
        f2 = formula2(kc, p, h)
        f4 = sum(p ** b * len(kc[b]['classes']) for b in range(h + 1))
        assert aG == f2, (name, h, aG, f2)
        assert aD == f4, (name, h, aD, f4)
        assert (aG - aD) % p ** (h + 1) == 0
        for a in range(h + 1):
            b = h - a
            k = len(kc[b]['classes'])
            assert (k - fixed_classes(kc[b]['perm'], p ** a)) % p ** (a + 1) == 0
            orbit_checks += 1
        if formula2(kc, p, h, shift=1) != aG:
            mutations['use_alpha_p^(a+1)'] += 1
        # Replace classes fixed by alpha^(p^a) by actual subgroups fixed by it.
        actual_fixed = 0
        for b in range(h + 1):
            ap = compose_power(alpha, p ** (h - b))
            actual_fixed += p ** b * sum(1 for V in kc[b]['subs']
                                         if frozenset(ap[x] for x in V) == V)
        if actual_fixed != aG:
            mutations['actual_subgroups_fixed_by_alpha_not_classes'] += 1
        if (aG - aD) % p ** (h + 2) != 0:
            mutations['modulus_p^(h+2)'] += 1
        rows.append({'h': h, 'semidirect': aG, 'direct': aD,
                     'v_p(difference)': min(vp(aG - aD, p), 99)})
    pc = parametrization_check(N, alpha, Lq, p, G, lg, kc, depth)
    return {'name': name, 'p': p, 'kernel_order': N.n, 'alpha_order': perm_order(alpha),
            'quotient_exponent_L': Lq, 'group_order': G.n, 'depth': depth,
            'rows': rows, 'orbit_divisibility_checks': orbit_checks,
            'parametrization_subgroups_checked': pc, 'bridge': bridge_note}


# ----------------------------------------------------------- theorem checks
def theorem_case(name, N, alpha, p, Lq, bridge, t, mutations, sc=True):
    """E = N_hat semidirect Z_p of length t; N = N_hat/M with M generated by
    p^bridge-th powers; Lq with alpha^(p^Lq)=1 on N. Valid range h<=bridge."""
    G = semidirect(N, alpha, Lq, p)
    lv = descent(G, range(G.n), p, bridge)
    kc = kernel_classes(N, alpha, p, bridge)
    ct = c_t(p, t)
    rows, open_checks, sc_checks = [], 0, 0
    for h in range(bridge + 1):
        a = len(lv[h])
        assert a == formula2(kc, p, h)
        A = A_ht(p, t, h)
        assert (a - A) % p ** (h + 1) == 0
        assert vp(a - ct, p) >= h + 1
        rows.append({'h': h, 'a_h': a, 'A_h(t)': A,
                     'v_p(a-A)': min(vp(a - A, p), 99),
                     'v_p(a-c_t)': min(vp(a - ct, p), 99)})
        if vp(a - ct, p) < h + 2:
            mutations['c_t_modulus_p^(h+2)'] += 1
    # every open U of index p^u with u < bridge: a_j(U) == c_t mod p^(j+1)
    for u in range(1, bridge):
        for U in lv[u]:
            sub = descent(G, U, p, bridge - u)
            for j in range(1, bridge - u + 1):
                assert vp(len(sub[j]) - ct, p) >= j + 1
                assert (len(sub[j]) - A_ht(p, t, j)) % p ** (j + 1) == 0
                open_checks += 1
            if sc:
                sc_checks += sc_for(G, U, sub, p, bridge - u)
    if sc:
        sub = descent(G, range(G.n), p, bridge)
        sc_checks += sc_for(G, frozenset(range(G.n)), sub, p, bridge)
    return {'name': name, 'p': p, 'length_t': t, 'kernel_order': N.n,
            'alpha_order': perm_order(alpha), 'quotient_exponent_L': Lq,
            'group_order': G.n, 'bridge_depth': bridge, 'rows': rows,
            'open_subgroup_residue_checks': open_checks,
            'sc_transitive_checks': sc_checks}


def sc_for(G, U, sub, p, depth):
    """(SC) on U for transitive X=U/W, W of index p^m, V of index p^h,
    m,h<=depth. Fixed points computed as x^-1 V x <= W (no use of (5))."""
    checks = 0
    for m in range(depth + 1):
        for W in sub[m]:
            reps, rem = [], set(U)
            while rem:
                x = min(rem)
                reps.append(x)
                rem -= {G.t[x][w] for w in W}
            # V fixes the coset xW iff V <= x W x^-1; no use of identity (5).
            conjW = [frozenset(G.conj(x, w) for w in W) for x in reps]
            for h in range(depth + 1):
                total = 0
                for V in sub[h]:
                    fix = sum(1 for C in conjW if len(V) <= len(C) and V <= C)
                    total += fix - len(reps)
                assert total % p ** (h + 1) == 0
                checks += 1
    return checks


def run():
    from collections import Counter
    mutations = Counter()
    out = {'lemma1_finite_kernels': [], 'theorem_A_quotients': []}

    # --- Lemma 1, all p-power-order automorphisms of small nonabelian kernels
    fk = []
    for name, N, p, Lq, depth in [
            ('D16', dihedral(8), 2, 3, 3),
            ('C4_semidirect_C4', metacyclic(4, 4, 3), 2, 3, 3),
            ('Q8', quaternion8(), 2, 3, 3),
            ('Heis_F3', heis(3), 3, 2, 2),
            ('M27=C9_semidirect_C3', metacyclic(9, 3, 4), 3, 2, 2)]:
        autos = pgroup_automorphisms(N, p)
        kc0 = kernel_classes(N, tuple(range(N.n)), p, depth)
        moved = 0
        start = len(fk)
        for i, alpha in enumerate(autos):
            r = lemma1_case(f'{name}#{i}', N, alpha, p, Lq, depth, mutations,
                            'finite kernel; alpha^(p^L)=1; h<=L')
            fk.append(r)
            kc = kernel_classes(N, alpha, p, depth)
            moved += any(kc[b]['perm'] != list(range(len(kc[b]['perm'])))
                         for b in range(depth + 1))
        mine = fk[start:]
        out['lemma1_finite_kernels'].append(
            {'kernel': name, 'p': p, 'p_power_automorphisms': len(autos),
             'automorphisms_moving_some_class': moved,
             'nonnormal_kernel_subgroups': sum(
                 len(cl) > 1 for b in range(depth + 1) for cl in kc0[b]['classes']),
             'cases_semidirect_ne_direct': sum(
                 any(row['semidirect'] != row['direct'] for row in r['rows'])
                 for r in mine),
             'L': Lq, 'depth': depth})
    out['lemma1_case_count'] = len(fk)
    out['lemma1_parametrized_subgroups'] = sum(
        r['parametrization_subgroups_checked'] for r in fk)
    out['lemma1_orbit_divisibility_checks'] = sum(
        r['orbit_divisibility_checks'] for r in fk)
    # p=5 abelian torsion kernel, a few shears
    N = zmod_tuple_group([5, 5])
    for A in ([[1, 1], [0, 1]], [[1, 0], [3, 1]], [[1, 2], [0, 1]]):
        alpha = matrix_action(N, [5, 5], A, 5)
        fk5 = lemma1_case(f'C5^2_{A}', N, alpha, 5, 2, 2, mutations,
                          'finite kernel; alpha^(25)=1; h<=2')
        out['lemma1_finite_kernels'].append({'kernel': f'C5^2 shear {A}', 'p': 5,
                                             'rows': fk5['rows']})

    # Infinite kernel with torsion: N = Z_p x C_p, alpha(x,c) = (x, c + x mod p).
    # N/(p^L Z_p x 0) is used; that kernel is alpha-stable and consists of
    # p^L-th powers, so h <= L is captured exactly.
    tors = []
    for p, L in [(2, 3), (3, 2)]:
        N = zmod_tuple_group([p ** L, p])
        ix = {x: i for i, x in enumerate(N.el)}
        alpha = tuple(ix[(x, (c + x) % p)] for x, c in N.el)
        r = lemma1_case(f'Z{p}xC{p}_mixing_mod{p ** L}', N, alpha, p, L, L, mutations,
                        'infinite torsion kernel; h<=L')
        tors.append({'kernel': f'Z_{p} x C_{p}', 'p': p, 'rows': r['rows']})
    out['lemma1_infinite_torsion_kernels'] = tors

    # --- Theorem A on torsion-free poly-Z_p quotients (bridge depth B)
    tc = []
    # p=2, length 3: Z_2^2 by the swap and by [[-1,1],[0,1]], coordinates mod 8
    for A in ([[0, 1], [1, 0]], [[-1, 1], [0, 1]], [[3, 0], [0, 1]]):
        N = zmod_tuple_group([8, 8])
        alpha = matrix_action(N, [8, 8], A, 8)
        o = perm_order(alpha)
        Lq = max(3, o.bit_length() - 1)
        assert 2 ** Lq % o == 0
        tc.append(theorem_case(f'Z2^2_by_{A}_mod8', N, alpha, 2, Lq, 3, 3, mutations))
    # p=3, length 3: Z_3^2 by [[4,1],[3,1]] mod 9
    N = zmod_tuple_group([9, 9])
    alpha = matrix_action(N, [9, 9], [[4, 1], [3, 1]], 9)
    o = perm_order(alpha)
    Lq = 2
    assert 9 % o == 0
    tc.append(theorem_case('Z3^2_by_[[4,1],[3,1]]_mod9', N, alpha, 3, Lq, 2, 3, mutations))
    # p=2, length 4: Heisenberg(Z_2) by X->X, Y->XY and by the swap X<->Y.
    # The coordinate kernel mod 4 is NOT stable under X->X, Y->XY at p=2
    # ((XY)^4 has z-coordinate 2 mod 4), so use the verbal subgroup E^4 =
    # {x,y = 0 mod 4, z = 0 mod 2}: characteristic and generated by 4th powers.
    assert extend_hom(heis(4), [heis(4).el.index((1, 0, 0)), heis(4).el.index((0, 1, 0))],
                      [heis(4).el.index((1, 0, 0)), heis(4).el.index((1, 1, 1))]) is None
    for nm, imgs in [('X->X,Y->XY', lambda H, X, Y: (X, H.t[X][Y])),
                     ('X<->Y', lambda H, X, Y: (Y, X))]:
        H = heis(4, 2)
        X, Y = H.el.index((1, 0, 0)), H.el.index((0, 1, 0))
        alpha = extend_hom(H, [X, Y], list(imgs(H, X, Y)))
        assert alpha is not None, 'automorphism does not preserve the kernel'
        o = perm_order(alpha)
        Lq = max(2, o.bit_length() - 1)
        assert 2 ** Lq % o == 0
        tc.append(theorem_case(f'Heis(Z2)_by_{nm}_mod4', H, alpha, 2, Lq, 2, 4,
                               mutations, sc=False))
    # p=2, length 4: Z_2^3 by unipotent Jordan block, mod 4
    N = zmod_tuple_group([4, 4, 4])
    alpha = matrix_action(N, [4, 4, 4], [[1, 1, 0], [0, 1, 1], [0, 0, 1]], 4)
    tc.append(theorem_case('Z2^3_by_J3_mod4', N, alpha, 2, 3, 2, 4, mutations, sc=False))
    out['theorem_A_quotients'] = tc

    # --- Sharpness: Heisenberg a_1 against A_1(3) and c_3, p=2,3,5,7
    sharp = []
