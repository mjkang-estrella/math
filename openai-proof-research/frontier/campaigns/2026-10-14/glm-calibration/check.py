def cert_ReN_blocks(N, Cks):
    """Re N = (N + N*)/2 reordered (1,3,5 | 2,4,6) is [[0,C],[C*,0]]."""
    ReN = (N + N.conjugate().T) / 2
    odd = [0, 2, 4]
    even = [1, 3, 5]
    ok = True
    msgs = []
    for a in odd:
        for b in odd:
            if not is_zero_expr(ReN[a, b]):
                ok = False
                msgs.append("odd-odd block entry (%d,%d) nonzero" % (a, b))
    for a in even:
        for b in even:
            if not is_zero_expr(ReN[a, b]):
                ok = False
                msgs.append("even-even block entry (%d,%d) nonzero" % (a, b))
    Cup = sp.Matrix(3, 3, lambda i, j: ReN[odd[i], even[j]])
    Clo = sp.Matrix(3, 3, lambda i, j: ReN[even[i], odd[j]])
    if not exact_eq(Cup, C_DISPLAYED):
        ok = False
        msgs.append("upper off-diagonal block != displayed C")
    if not exact_eq(Clo, C_DISPLAYED.conjugate().T):
        ok = False
        msgs.append("lower off-diagonal block != C*")
    return ok, ("Hermitian part (N+N*)/2, reordered (1,3,5|2,4,6), has zero "
                "diagonal blocks and off-diagonal blocks C, C* equal to the "
                "displayed C" if ok else "; ".join(msgs))


