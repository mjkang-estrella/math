def words_upto(L):
    """All words of length <= L in {N, N*} (0 = identity), as a flat list."""
    if L in WORDS_CACHE:
        return WORDS_CACHE[L]
    mats = [sp.eye(6)]
    cur = [sp.eye(6)]
    for _ in range(L):
        nxt = [W * build_N() for W in cur] + [W * build_N().conjugate().T
                                              for W in cur]
        mats += nxt
        cur = nxt
    WORDS_CACHE[L] = mats
    return mats


