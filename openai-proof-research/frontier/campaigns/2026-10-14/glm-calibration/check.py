def cert_Pencil_theta(N, Cks):
    """charpoly of Re(e^{-i theta} N) is theta-independent and equals
    (t^2-1)^2 (t^2 - 7/64); verified symbolically in c=cos, s=sin reduced
    modulo c^2 + s^2 - 1."""
    c, s = symbols('c s')
    A = sp.MutableDenseMatrix(6, 6, lambda i, j: expand0(
        ((c - I * s) * N[i, j] + (c + I * s) * N.conjugate().T[i, j]) / 2))
    cp = sp.Poly(A.charpoly(T).as_expr(), T)
    G = sp.groebner([c ** 2 + s ** 2 - 1], c, s, order='lex',
                    domain=sp.QQ.frac_field(s2, s7))
    coeffs = {}
    for (deg,), coef in cp.terms():
        _, rmd = G.reduce(sp.Poly(sp.expand(coef), c, s))
        coeffs[deg] = sp.expand(rmd.as_expr())
    expected = sp.expand((T ** 2 - 1) ** 2 * (T ** 2 - R(7, 64)))
    exp_coeffs = {d: sp.expand(sp.Poly(expected, T).coeff_monomial(T ** d))
                  for d in range(7)}
    exp_coeffs = {d: v for d, v in exp_coeffs.items() if v != 0}
    ok = coeffs == exp_coeffs
    return ok, ("charpoly Re(e^{-i theta} N), reduced mod c^2+s^2=1, is "
                "theta-independent and equals (t^2-1)^2 (t^2-7/64): every "
                "support pencil has eigenvalues 1,1,-1,-1,sqrt(7)/8,-sqrt(7)/8"
                if ok else "reduced charpoly coefficients %s" % coeffs)


def cert_PN_construction(N, Cks):
    """Cross-check the base-first assembly against SymPy's TensorProduct."""
    PN = build_PN(N, Cks)
    from sympy.physics.quantum import TensorProduct
    ref = sp.MutableDenseMatrix(12, 12, lambda i, j: 0)
    Nk = sp.eye(6)
    for k in range(4):
        if k > 0:
            Nk = Nk * N
        ref = ref + sp.Matrix(TensorProduct(Nk, Cks[k]).doit())
    ok = exact_eq(PN, ref)
    return ok, ("P[N] = sum_k N^k (x) C_k, index 2i+j (base-first), matches "
                "an independent TensorProduct assembly"
                if ok else "assembly mismatch vs TensorProduct")


def cert_Tensor_convention(N, Cks):
    """The fiber-first convention must NOT satisfy P[N] x = 2 y."""
    PN = build_PN(N, Cks)
    PA = build_PN_fiberfirst(N, Cks)
    x, y = vec_x(), vec_y()
    ok1 = not exact_eq(PA, PN)
    ok2 = not exact_eq(PA * x, 2 * y)
    ok3 = exact_eq(PN * x, 2 * y)
    ok = ok1 and ok2 and ok3
    return ok, ("fiber-first assembly sum_k C_k (x) N^k differs from P[N] "
                "and fails P[N]x=2y (difference %s), while the base-first "
                "assembly satisfies it"
                % ("nonzero" if ok2 else "ZERO -- convention not distinguished")
                if ok else "convention test failed")


