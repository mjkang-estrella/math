def cert_Cyclic_rank(N, Cks):
    ranks = {}
    e1 = sp.eye(6)[:, 0]
    minL = None
    for L in range(0, 6):
        Ws = words_upto(L)
        Mx = sp.Matrix.hstack(*[W * e1 for W in Ws])
        ranks[L] = Mx.rank()
        if ranks[L] == 6 and minL is None:
            minL = L
    ok = (minL == 4)
    detail = "rank of {W e1 : words |W| <= L}: %s" % ranks
    # claimed vector identities
    Nst = N.conjugate().T
    v1 = Nst * e1
    v2 = Nst ** 2 * e1
    v3 = Nst ** 3 * e1
    e2 = sp.zeros(6, 1); e2[1] = 1
    e4 = sp.zeros(6, 1); e4[3] = 1
    e3 = sp.zeros(6, 1); e3[2] = 1
    e5 = sp.zeros(6, 1); e5[4] = 1
    e6 = sp.zeros(6, 1); e6[5] = 1
    id_ok = exact_eq(v1, R(6, 5) * e2 + s14 / 5 * e4) and \
        exact_eq(v2, R(3, 2) * e3 + s14 / 4 * e5) and \
        exact_eq(v3, s7 / 2 * e6)
    detv = expand0(R(3, 2) * (-3 * s2 / 4) - (s14 / 4) * (s7 / 2))
    det_ok = detv == -2 * s2
    # word-space dimension of the unital *-algebra: 36 at length <= 6
    Ws6 = words_upto(6)
    Mv = sp.Matrix.hstack(*[sp.Matrix(list(W)).reshape(36, 1) for W in Ws6])
    dim6 = Mv.rank()
    ok = ok and id_ok and det_ok and dim6 == 36
    return ok, (detail + "; minimal L with cyclic rank 6 is %s; N*e1, "
                "N*^2 e1, N*^3 e1 as claimed; det[(3/2,sqrt14/4),"
                "(sqrt7/2,-3sqrt2/4)] = -2sqrt2; word-space dimension of the "
                "unital *-algebra generated by N is 36 at word length <= 6, "
                "i.e. the *-algebra is all of M_6(C)"
                % minL if ok else
                detail + "; identities ok=%s det ok=%s dim6=%s"
                % (id_ok, det_ok, dim6))


def cert_Boundary_PP(N, Cks):
    """P(z) P(z)* = I on |z| = 1, with P built from the derived C_k."""
    z, w = symbols('z w')
    P = sp.MutableDenseMatrix(2, 2, lambda i, j: 0)
    Pst = sp.MutableDenseMatrix(2, 2, lambda i, j: 0)
    for k, Ck in enumerate(Cks):
        P = P + Ck * z ** k
        Pst = Pst + Ck.conjugate().T * w ** k  # conj(P)(z): z -> w
    PP = P * Pst
    G = sp.groebner([z * w - 1], z, w, order='lex',
                    domain=sp.QQ.frac_field(s7))
    ok = True
    for i in range(2):
        for j in range(2):
            _, rmd = G.reduce(sp.Poly(sp.expand(PP[i, j]), z, w))
            if sp.expand(rmd.as_expr()) != (1 if i == j else 0):
                ok = False
    return ok, ("P(z) P(z)* = I reduced modulo z w = 1 (w = conj z, |z| = 1): "
                "the two columns of P are orthogonal unit vectors on the "
                "circle" if ok else "boundary identity fails")


def cert_Spot_check_scalar_channel(N, Cks):
    """36 exact unit pairs (u,v): ||(v* P u)(N)||^2 <= 849/256, decided by
    exact principal-minor PSD test on 849/256 I - M*M.  Sampled instances
    only; the universal quantifier remains an analytic claim."""
    unit_vecs = {
        'f1': sp.Matrix([1, 0]),
        'f2': sp.Matrix([0, 1]),
        '(1,1)/s2': sp.Matrix([1, 1]) / sqrt(2),
        '(1,-1)/s2': sp.Matrix([1, -1]) / sqrt(2),
        '(1,i)/s2': sp.Matrix([1, I]) / sqrt(2),
        '(1,-i)/s2': sp.Matrix([1, -I]) / sqrt(2),
    }
    bad = []
    total = 0
    for un, u in unit_vecs.items():
        for vn, v in unit_vecs.items():
            M = sp.zeros(6, 6)
            Nk = sp.eye(6)
            for k in range(4):
                if k > 0:
                    Nk = Nk * N
                ck = expand0((v.conjugate().T * Cks[k] * u)[0, 0])
                if ck != 0:
                    M = M + ck * Nk
            G = R(849, 256) * sp.eye(6) - M.conjugate().T * M
            total += 1
            if not psd_hermitian(G):
                bad.append((un, vn))
    ok = not bad
    return ok, ("%d/%d exact sampled pairs (u,v) satisfy ||(v*Pu)(N)||^2 <= "
                "849/256 = (sqrt(849)/16)^2 via exact principal-minor PSD "
                "tests" % (total - len(bad), total)
                if ok else "bound violated for pairs %s" % bad[:5])


