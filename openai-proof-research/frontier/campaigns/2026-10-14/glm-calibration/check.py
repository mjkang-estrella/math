def build_N(overrides=None):
    N = sp.zeros(6, 6)
    spec = dict(N_SPEC)
    if overrides:
        spec.update(overrides)
    for (i, j), v in spec.items():
        N[i, j] = v
    return N


def build_Cks(p_overrides=None):
    """Derive C_0..C_3 symbolically from the displayed polynomial P(z)."""
    over = dict(p_overrides or {})
    Cks = []
    for k in range(4):
        Ck = sp.MutableDenseMatrix(2, 2, lambda i, j: 0)
        for i in range(2):
            for j in range(2):
                poly = sp.Poly(P_Z[i, j], Z_SYMBOL)
                v = poly.coeff_monomial(Z_SYMBOL ** k) if k <= poly.degree() else 0
                if (i, j) == (0, 0) and k == 2 and (0, 0) in over:
                    v = over[(0, 0)]
                if (i, j) == (1, 0) and k == 1 and (1, 0) in over:
                    v = over[(1, 0)]
                Ck[i, j] = v
        Cks.append(Ck)
    return Cks


def build_PN(N, Cks):
    """Base-first P[N] = sum_k N^k (x) C_k on E(6) (x) F(2).

    Convention under test: index 2*i + j, i.e.
    P[N][2*i+j, 2*i'+j'] = sum_k (N^k)_{i,i'} (C_k)_{j,j'}.
    """
    PN = sp.MutableDenseMatrix(12, 12, lambda i, j: 0)
    Nk = sp.eye(6)
    for k in range(4):
        if k > 0:
            Nk = Nk * N
        for i in range(6):
            for ip in range(6):
                v = Nk[i, ip]
                if v != 0:
                    for j in range(2):
                        for jp in range(2):
                            w = Cks[k][j, jp]
                            if w != 0:
                                PN[2 * i + j, 2 * ip + jp] = \
                                    PN[2 * i + j, 2 * ip + jp] + v * w
    return PN


