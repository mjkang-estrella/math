def cert_Grading(N, Cks):
    from collections import Counter
    dims = Counter(grade_of(i) for i in range(12))
    expected_dims = {0: 1, 1: 3, 2: 4, 3: 3, 4: 1}
    ok = dict(dims) == expected_dims
    msg = "grade dimensions %s" % (sorted(dims.items()),)
    # per-term: each N^k (x) C_k raises grade by exactly 2
    Nk = sp.eye(6)
    for k in range(4):
        if k > 0:
            Nk = Nk * N
        for i in range(6):
            for ip in range(6):
                if Nk[i, ip] != 0:
                    for j in range(2):
                        for jp in range(2):
                            if Cks[k][j, jp] != 0:
                                # (N^k)_{i,ip}(C_k)_{j,jp} maps e_ip (x) f_j
                                # to e_i (x) f_jp
                                g_in = H0[ip] + GF[jp]
                                g_out = H0[i] + GF[j]
                                if g_out != g_in + 2:
                                    ok = False
    PN = build_PN(N, Cks)
    for a in range(12):
        for b in range(12):
            if PN[b, a] != 0 and grade_of(b) != grade_of(a) + 2:
                ok = False
    return ok, (msg + "; every nonzero entry of P[N] maps grade g to g+2"
                if ok else msg + "; raise-by-two violated")


