def expand0(expr):
    return sp.expand(sp.radsimp(sp.expand(expr)))


def is_zero_expr(expr):
    return expand0(expr) == 0


def exact_eq(A, B):
    """Exact equality of sympy matrices/expressions over Q(sqrt2,sqrt7,...)."""
    if isinstance(A, sp.MatrixBase) or isinstance(B, sp.MatrixBase):
        if not (isinstance(A, sp.MatrixBase) and isinstance(B, sp.MatrixBase)):
            return False
        if A.shape != B.shape:
            return False
        return all(is_zero_expr(A[i, j] - B[i, j]) for i in range(A.rows)
                   for j in range(A.cols))
    return is_zero_expr(A - B)


def field_sign(expr):
    """Exact sign of a real element of Q(sqrt2, sqrt7, sqrt14).

    Represents the value as a + b*sqrt2 + c*sqrt7 + d*sqrt14 with rational
    a,b,c,d and decides the sign with rigorous rational interval bounds for
    the square roots (integer isqrt; no floating point).  Returns +1 / -1.
    """
    e = expand0(expr)
    if is_zero_expr(e):
        return 0
    if e.coeff(I) != 0:
        raise ValueError("field_sign: expression is not real: %s" % e)
    d = e.coeff(s14)
    e = expand0(e - d * s14)
    c = e.coeff(s7)
    e = expand0(e - c * s7)
    b = e.coeff(s2)
    a = expand0(e - b * s2)
    coefs = [F(str(a)), F(str(b)), F(str(c)), F(str(d))]
    if coefs[1:] == [F(0)] * 3 and coefs[0] != 0:
        return 1 if coefs[0] > 0 else -1
    for k in (12, 24, 48, 96, 192, 384, 768):
        sc = 10 ** k

        def bnd(n):
            r = math.isqrt(n * sc * sc)
            return F(r, sc), F(r + 1, sc)

        lo2, hi2 = bnd(2)
        lo7, hi7 = bnd(7)
        lo14, hi14 = bnd(14)
        L = F(0)
        U = F(0)
        for coef, lo, hi in zip(coefs, (F(1), lo2, lo7, lo14),
                                (F(1), hi2, hi7, hi14)):
            t1, t2 = coef * lo, coef * hi
            L += min(t1, t2)
            U += max(t1, t2)
        if L > 0:
            return 1
        if U < 0:
            return -1
    raise ValueError("field_sign: interval did not decide %s" % (coefs,))


def psd_hermitian(G):
    """Exact PSD test for a Hermitian matrix: all principal minors >= 0."""
    n = G.rows
    for r in range(1, n + 1):
        for S in itertools.combinations(range(n), r):
            d = expand0(G[list(S), list(S)].det())
            if d == 0:
                continue
            if field_sign(d) < 0:
                return False
    return True


