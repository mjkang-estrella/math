"""360575 (Kim-Lee-Oh arXiv:2310.20571, Conj. conj:on indecomp): for skew shapes lambda/mu that are disconnected and contain no
disconnected ribbon (no two consecutive connected components both ribbons), is M_P indecomposable?
M_P = B([sigma,rho]_L) with basis read_{tau_0}(SYT(lambda/mu)) (source Thm 'interval description', Def WBI action);
tau_0 fills 1..n right-to-left starting with the top row; read_tau(T)(k) = T(tau^{-1}(k)).
pi_i . g = g if i in Des_L(g); 0 if s_i g not in basis; s_i g otherwise (s_i g swaps values i,i+1).
M is cyclic on sigma (source line 3810), so End(M) = {v : m(v)=0 whenever m(sigma)=0, m(v)=m'(v) whenever m(sigma)=m'(sigma)},
m ranging over the monoid generated by the pi_i.  Indecomposable <=> End local <=> dim End - dim rad End = 1 (over C);
rad via the trace form (Dickson) computed mod a large prime P (diagnostic; char P >> dim)."""
import sys, itertools
P = 2_147_483_629
def partitions(n, maxpart=None):
    if maxpart is None: maxpart = n
    if n == 0: yield (); return
    for k in range(min(n, maxpart), 0, -1):
        for rest in partitions(n - k, k): yield (k,) + rest
def skew_shapes(n, maxrows=None):
    seen = set()
    for size in range(n, 3 * n + 1):
        for lam in partitions(size):
            for musz in [size - n]:
                for mu in partitions(musz) if musz else [()]:
                    if len(mu) > len(lam) or any(m > l for m, l in zip(mu, lam)): continue
                    mu2 = tuple(mu) + (0,) * (len(lam) - len(mu))
                    cells = frozenset((r, c) for r in range(len(lam)) for c in range(mu2[r], lam[r]))
                    # normalise: drop empty rows/cols (translate)
                    if any(lam[r] == mu2[r] for r in range(len(lam))): continue
                    if min(c for r, c in cells) != 0: continue
                    if cells in seen: continue
                    seen.add(cells); yield lam, mu2, cells
        if size > 2 * n + 2: break
def components(cells):
    cells = set(cells); comps = []
    while cells:
        st = [cells.pop()]; comp = {st[0]}
        while st:
            r, c = st.pop()
            for d in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                x = (r + d[0], c + d[1])
                if x in cells: cells.remove(x); comp.add(x); st.append(x)
        comps.append(comp)
    comps.sort(key=lambda C: min(r for r, c in C))  # top to bottom (= NE to SW order in star product)
    return comps
def is_ribbon(C): return not any((r, c) in C and (r + 1, c) in C and (r, c + 1) in C and (r + 1, c + 1) in C for r, c in C)
def basis(cells):
    rows = sorted({r for r, c in cells}); n = len(cells)
    order = [x for r in rows for x in sorted([x for x in cells if x[0] == r], key=lambda x: -x[1])]  # tau_0^{-1}(k)
    res = []
    cl = sorted(cells)
    def rec(T, k):
        if k > n: res.append(tuple(T[order[i]] for i in range(n))); return
        for x in cl:
            if x in T: continue
            r, c = x
            if (r - 1, c) in cells and (r - 1, c) not in T: continue
            if (r, c - 1) in cells and (r, c - 1) not in T: continue
            T[x] = k; rec(T, k + 1); del T[x]
    rec({}, 1)
    return res
def analyse(cells):
    Bs = basis(cells); n = len(cells); d = len(Bs); idx = {g: i for i, g in enumerate(Bs)}
    pos = [{v: j for j, v in enumerate(g)} for g in Bs]
    act = []  # act[i][b] -> image index or -1 ; 'b' itself if descent
    for i in range(1, n):
        a = []
        for b, g in enumerate(Bs):
            if pos[b][i + 1] < pos[b][i]: a.append(b)
            else:
                h = tuple(i + 1 if v == i else i if v == i + 1 else v for v in g)
                a.append(idx.get(h, -1))
        act.append(a)
    sig = min(range(d), key=lambda b: sum(1 for i in range(n) for j in range(i + 1, n) if Bs[b][i] > Bs[b][j]))
    # representatives m_g (partial maps) with m_g(sigma)=g, via BFS from sigma along pi_i; then
    # f_v(g) := m_g(v) is a module map iff it intertwines every pi_i on every basis element g.
    reps = {sig: tuple(range(d))}; queue = [sig]
    while queue:
        g = queue.pop(0)
        for a in act:
            h = a[g]
            if h >= 0 and h not in reps:
                reps[h] = tuple(a[x] if x >= 0 else -1 for x in reps[g]); queue.append(h)
    assert len(reps) == d, 'sigma not a cyclic generator?'
    eqset = set(); eqs = []
    def addeq(m, mr):
        rows = {}
        for b in range(d):
            t = m[b]
            if t >= 0: rows.setdefault(t, {}); rows[t][b] = (rows[t].get(b, 0) + 1) % P
            if mr is not None:
                t2 = mr[b]
                if t2 >= 0: rows.setdefault(t2, {}); rows[t2][b] = (rows[t2].get(b, 0) - 1) % P
        for r in rows.values():
            key = frozenset((k, v) for k, v in r.items() if v)
            if key and key not in eqset: eqset.add(key); eqs.append(dict(key))
    for g in range(d):
        mg = reps[g]
        for a in act:
            pm = tuple(a[x] if x >= 0 else -1 for x in mg)   # pi_i o m_g
            h = a[g]
            if h == g: addeq(pm, mg)
            elif h < 0: addeq(pm, None)
            else: addeq(reps[h], pm)
    seen = reps
    # Gaussian elimination mod P -> nullspace basis of equations
    piv = {}
    for r in eqs:
        r = dict(r)
        while r:
            k = max(r)
            if k in piv:
                pr = piv[k]; f = r[k]
                for kk, vv in pr.items():
                    r[kk] = (r.get(kk, 0) - f * vv) % P
                    if r[kk] == 0: del r[kk]
            else:
                inv = pow(r[k], P - 2, P); r = {kk: vv * inv % P for kk, vv in r.items()}; piv[k] = r; break
    free = [b for b in range(d) if b not in piv]
    # nullspace vectors: for each free variable f, set it 1, solve pivots (pivot k depends on smaller indices only)
    sol = []
    for f in free:
        v = [0] * d; v[f] = 1
        for k in sorted(piv):
            s = sum(vv * v[kk] for kk, vv in piv[k].items() if kk != k) % P
            v[k] = (-s) % P
        sol.append(v)
    e = len(sol)
    def apply(m, v):
        w = [0] * d
        for b, c in enumerate(v):
            if c and m[b] >= 0: w[m[b]] = (w[m[b]] + c) % P
        return w
    def compose(u, v):  # f_u o f_v corresponds to f_u(v) = sum_g v_g * reps[g](u)
        w = [0] * d
        for g, c in enumerate(v):
            if c:
                x = apply(reps[g], u)
                for j in range(d):
                    if x[j]: w[j] = (w[j] + c * x[j]) % P
        return w
    # express vectors in solution basis via pivot coordinates (free coords)
    def coords(w): return [w[f] for f in free]
    mult = [[coords(compose(sol[i], sol[j])) for j in range(e)] for i in range(e)]
    # left-regular trace: Tr(L_x) for basis x_k: L_{x_k}(x_j) = sum_l mult[k][j][l] x_l ; tr = sum_j mult[k][j][j]
    trL = [sum(mult[k][j][j] for j in range(e)) % P for k in range(e)]
    # trace form t(x_i,x_j) = Tr(L_{x_i x_j}) = sum_l mult[i][j][l]*trL[l]
    G = [[sum(mult[i][j][l] * trL[l] for l in range(e)) % P for j in range(e)] for i in range(e)]
    # rank of G mod P = dim E - dim rad
    M = [row[:] for row in G]; rank = 0
    for c in range(e):
        p = next((r for r in range(rank, e) if M[r][c]), None)
        if p is None: continue
        M[rank], M[p] = M[p], M[rank]; inv = pow(M[rank][c], P - 2, P)
        M[rank] = [x * inv % P for x in M[rank]]
        for r in range(e):
            if r != rank and M[r][c]:
                f = M[r][c]; M[r] = [(x - f * y) % P for x, y in zip(M[r], M[rank])]
        rank += 1
    return d, e, rank, len(seen)
def connected_shapes(k):
    out = []; seen = set()
    for lam, mu, cells in skew_shapes(k):
        if len(components(cells)) != 1: continue
        r0 = min(r for r, c in cells); c0 = min(c for r, c in cells)
        key = frozenset((r - r0, c - c0) for r, c in cells)
        if key not in seen: seen.add(key); out.append(key)
    return out
def star(seq):
    # place components from top-right to bottom-left, each strictly below and strictly left of the previous
    cells = set(); top = 0; placed = []
    widths = [max(c for r, c in C) + 1 for C in seq]; heights = [max(r for r, c in C) + 1 for C in seq]
    W = sum(widths); col = W
    for C, w, h in zip(seq, widths, heights):
        col -= w
        for r, c in C: cells.add((top + r, col + c))
        top += h
    return frozenset(cells)
