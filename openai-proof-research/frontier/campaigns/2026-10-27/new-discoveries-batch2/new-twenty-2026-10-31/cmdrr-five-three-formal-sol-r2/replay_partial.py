"""Source-only fresh rebuild of the existing PARTIAL development, not the endpoint.
All binary outputs are generated by pinned Lean/checker within this lane.
"""
import os, json, hashlib, subprocess
from pathlib import Path
lane=Path(__file__).resolve().parent
os.chdir(lane)
mods=['CMDRRBase','CMDRROccurrence','CMDRRCells','CMDRRTransport','CMDRRSourceTransport','CMDRRRows','CMDRRCounts','CMDRRRepeat','CMDRRSwap','CMDRRNormalize','CMDRRAudit']
pins=json.loads(Path('PINS.json').read_text())
root=lane/'extracted'
build=root/'build'
build.mkdir(parents=True,exist_ok=True)
assert not list(build.iterdir()), 'Extracted build must be EMPTY'
env=os.environ.copy()
upstream=[p for p in env['LEAN_PATH'].split(':') if p!=str(lane/'build')]
assert all('/.lake/packages/' in p for p in upstream)
env['LEAN_PATH']=':'.join([str(build)]+upstream)
print('EXTRACTED_LEAN_PATH',env['LEAN_PATH'],flush=True)
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
before={}
for m in mods:
    src=Path('src')/(m+'.lean')
    rel=Path('extracted/src')/src.name
    subprocess.run(['python3','-I','-B','write_lane.py',str(rel)],input=src.read_text(),text=True,check=True)
    assert sha(src)==sha(rel)
    before[m]=sha(src)
commands=[]
for m in mods:
    cmd=[pins['lean_bin'],'-j1','-M3500','-DwarningAsError=true','-o',str(build/(m+'.olean')),str(root/'src'/(m+'.lean'))]
    print('COMMAND',json.dumps(cmd),flush=True)
    r=subprocess.run(cmd,env=env)
    commands.append({'module':m,'phase':'strict','exit':r.returncode})
    assert r.returncode==0
for m in mods:
    cmd=[pins['leanchecker_bin'],m]
    print('COMMAND',json.dumps(cmd),flush=True)
    r=subprocess.run(cmd,env=env)
    commands.append({'module':m,'phase':'leanchecker','exit':r.returncode})
    assert r.returncode==0
assert all(sha(Path('src')/(m+'.lean'))==before[m]==sha(root/'src'/(m+'.lean')) for m in mods)
report={'scope':'PARTIAL_ONLY_NO_NONEXISTENCE_ENDPOINT','empty_build_verified':True,'source_hashes_after_checker':before,'commands':commands,'lean_path':env['LEAN_PATH'],'oleans':{m:sha(build/(m+'.olean')) for m in mods}}
subprocess.run(['python3','-I','-B','write_lane.py','results/PARTIAL-REPLAY.json'],input=json.dumps(report,indent=2)+'\n',text=True,check=True)
print('PARTIAL_REPLAY_PASS',flush=True)
