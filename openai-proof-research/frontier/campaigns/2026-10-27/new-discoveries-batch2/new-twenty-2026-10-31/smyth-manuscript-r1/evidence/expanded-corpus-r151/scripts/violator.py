# Extract a Hall violator from the type-level flow and verify it by explicit enumeration.
import sys,collections,json
sys.path.insert(0,sys.argv[0].rsplit('/',1)[0])
from smyth import parts_count, combine, dom
A,a,B,b=map(int,sys.argv[1:5])
X=combine(parts_count(b,A),parts_count(a,B)); Y=combine(parts_count(a,A),parts_count(b,B))
xs=list(X); ys=list(Y); INF=10**18
# flow
S=('s',);T=('t',)
cap=collections.defaultdict(int); adj=collections.defaultdict(list)
def add(u,v,c):
    if v not in adj[u]: adj[u].append(v); adj[v].append(u)
    cap[(u,v)]+=c
for p in xs: add(S,('x',p),X[p])
for q in ys: add(('y',q),T,Y[q])
for p in xs:
    for q in ys:
        if dom(p,q): add(('x',p),('y',q),INF)
flow=0
while True:
    par={S:None}; dq=collections.deque([S])
    while dq and T not in par:
        u=dq.popleft()
        for v in adj[u]:
            if v not in par and cap[(u,v)]>0: par[v]=u; dq.append(v)
    if T not in par: break
    v=T;f=INF
    while par[v] is not None: u=par[v]; f=min(f,cap[(u,v)]); v=u
    v=T
    while par[v] is not None: u=par[v]; cap[(u,v)]-=f; cap[(v,u)]+=f; v=u
    flow+=f
reach=set(par)  # residual-reachable from S after final BFS
Sx=[p for p in xs if ('x',p) in reach]
print('flow',flow,'|X|',sum(X.values()),'|Y|',sum(Y.values()),'violator types',len(Sx))
# minimal generators (maximal elements of Sx in dominance)
gens=[p for p in Sx if not any(q!=p and dom(q,p) for q in Sx)]
print('maximal generators',gens)
# explicit verification by enumeration of compositions
def comps(n,m):
    if m==0:
        if n==0: yield ()
        return
    if m==1: yield (n,); return
    for i in range(n+1):
        for r in comps(n-i,m-1): yield (i,)+r
def srt(t): return tuple(sorted([z for z in t if z],reverse=True))
def domfull(p,q):
    p=sorted(p,reverse=True); q=sorted(q,reverse=True); sp=sq=0
    for i in range(max(len(p),len(q))):
        sp+=p[i] if i<len(p) else 0; sq+=q[i] if i<len(q) else 0
        if sp<sq: return False
    return True
Dgen=gens
SX=[(l,m) for l in comps(b,A) for m in comps(a,B) if any(domfull(g,l+m) for g in Dgen)]
NY=[(l,m) for l in comps(a,A) for m in comps(b,B) if any(domfull(g,l+m) for g in Dgen)]
# Hall: S = X-elements whose type lies in the down-set D generated by gens; N(S) subset of Y-elements with type in D
print('explicit |S|',len(SX),'explicit |Y cap D|',len(NY),'deficiency',len(SX)-len(NY))
json.dump({'A':A,'a':a,'B':B,'b':b,'flow':flow,'gens':gens,'S':len(SX),'YcapD':len(NY)},open(sys.argv[5],'w'))
