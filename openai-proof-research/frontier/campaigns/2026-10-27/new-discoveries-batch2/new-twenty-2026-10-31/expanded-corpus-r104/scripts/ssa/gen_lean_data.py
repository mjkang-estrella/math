# Emit Lean data: 4-ary trees (letters ordered A,C,G,T) for S membership, lower vector v, upper vector u.
import json,sys,itertools
D=sys.argv[1]; c=json.load(open(D+'/outputs/ssa5-certificate.json'))
S=set(c['S']); v=c['v']; u=c['u']; al='ACGT'
def tree(f,prefix=''):
    if len(prefix)==5: return f'.leaf {f(prefix)}'
    return '(.node ' + ' '.join('('+tree(f,prefix+a)+')' for a in al) + ')'
TC=lambda w: sum(ch in 'TC' for ch in w)>=3
out=['-- Generated by scripts/ssa/gen_lean_data.py from outputs/ssa5-certificate.json; do not edit.',
'import SSA5.Defs','','namespace SSA','',
f'/-- Membership tree of the improved generating set (512 words). -/\ndef sTree : QT Bool := {tree(lambda w: "true" if w in S else "false")}','',
f'/-- Lower certificate vector (nonnegative integers, indexed by words of S). -/\ndef vTree : QT ℕ := {tree(lambda w: v.get(w,0))}','',
f'/-- Upper certificate vector (positive integers on TC-dominant words). -/\ndef uTree : QT ℕ := {tree(lambda w: u.get(w,1))}','',
f'def lamNum : ℕ := {c["lam"][0]}\ndef lamDen : ℕ := {c["lam"][1]}\ndef muNum : ℕ := {c["mu"][0]}\ndef muDen : ℕ := {c["mu"][1]}',
f'def vMax : ℕ := {max(v.values())}\ndef uMin : ℕ := {min(u.values())}\ndef uMax : ℕ := {max(u.values())}',
'','end SSA','']
open(D+'/formal/SSA5/Data.lean','w').write('\n'.join(out))
w0=max(v,key=lambda w:v[w]); print('witness word with max v',w0,v[w0])
