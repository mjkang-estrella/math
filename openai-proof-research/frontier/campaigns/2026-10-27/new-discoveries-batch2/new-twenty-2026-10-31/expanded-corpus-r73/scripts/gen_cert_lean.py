# Generate formal/R73/Cert.lean from outputs/lean-certificate-445.json (integer tables, checked by decide).
import json,pathlib
D=pathlib.Path(__file__).resolve().parents[1]
c=json.loads((D/'outputs/lean-certificate-445.json').read_text())
coords=[tuple(x) for x in c['coords']]
def vec(xs): return '![' + ', '.join(xs) + ']'
def tab2(f,n1,n2): return vec([vec([str(f(a,b)) for b in range(n2)]) for a in range(n1)])
def split(w):
  d={coords[m]:w[m] for m in range(56)}
  return (lambda i,j: d[('12',i,j)]),(lambda i,k: d[('13',i,k)]),(lambda j,k: d[('23',j,k)])
A,B,C=c['A'],c['B'],c['C']
L=[]
L.append('import R73.Defs\n\n/-! Integer certificate data for the 4 × 4 × 5 facet (generated by scripts/gen_cert_lean.py). -/\n\nnamespace R73.Cert\n')
L.append('/-- Weight vector of a functional given by its `[12]`, `[13]`, `[23]` tables. -/')
L.append('def wt (a : Fin 4 → Fin 4 → ℤ) (b : Fin 4 → Fin 5 → ℤ) (c : Fin 4 → Fin 5 → ℤ) :\n    Margin 4 4 5 → ℤ\n  | Sum.inl (i, j) => a i j\n  | Sum.inr (Sum.inl (i, k)) => b i k\n  | Sum.inr (Sum.inr (j, k)) => c j k\n')
L.append('/-- Value of an integer functional on the column of a cell. -/')
L.append('def onCol (w : Margin 4 4 5 → ℤ) (c : Cell 4 4 5) : ℤ :=\n  w (Sum.inl (c.1, c.2.1)) + w (Sum.inr (Sum.inl (c.1, c.2.2))) + w (Sum.inr (Sum.inr (c.2.1, c.2.2)))\n')
L.append('/-- The facet-defining functional `ℓ`. -/')
L.append(f"def ellZ : Margin 4 4 5 → ℤ :=\n  wt {tab2(lambda i,j:A[i][j],4,4)}\n    {tab2(lambda i,k:B[i][k],4,5)}\n    {tab2(lambda j,k:C[j][k],4,5)}\n")
L.append('theorem ell_nonneg : ∀ c : Cell 4 4 5, 0 ≤ onCol ellZ c := by decide +kernel\n')
bc=[tuple(x) for x in c['basis']]
L.append('/-- 43 tight cells whose columns are linearly independent. -/')
L.append('def bcell : Fin 43 → Cell 4 4 5 :=\n  ' + vec([f'({i}, {j}, {k})' for i,j,k in bc]) + '\n')
L.append('theorem ell_basis : ∀ t : Fin 43, onCol ellZ (bcell t) = 0 := by decide +kernel\n')
c0=tuple(c['c0']); L.append(f'/-- A cell off the facet. -/\ndef c0 : Cell 4 4 5 := ({c0[0]}, {c0[1]}, {c0[2]})\n')
L.append(f'theorem ell_c0 : onCol ellZ c0 = 1 := by decide +kernel\n')
# Phi tables
Phi=c['Phi']
def three(w):
  a,b,cc=split(w); return f"wt {tab2(a,4,4)}\n      {tab2(b,4,5)}\n      {tab2(cc,4,5)}"
L.append('/-- Functionals biorthogonal to the 43 basis columns. -/')
L.append('def phiZ : Fin 43 → Margin 4 4 5 → ℤ :=\n  ' + vec(['(' + three(Phi[s]) + ')' for s in range(43)]) + '\n')
L.append('theorem phi_biorth : ∀ s t : Fin 43, onCol (phiZ s) (bcell t) = if s = t then 1 else 0 := by\n  decide +kernel\n')
Psi=c['Psi']
L.append('/-- Twelve linear relations satisfied by every column. -/')
L.append('def psiZ : Fin 12 → Margin 4 4 5 → ℤ :=\n  ' + vec(['(' + three(Psi[s]) + ')' for s in range(12)]) + '\n')
L.append('theorem psi_cols : ∀ (s : Fin 12) (c : Cell 4 4 5), onCol (psiZ s) c = 0 := by decide +kernel\n')
def mg(m):
  t,a,b=coords[m]
  return {'12':f'Sum.inl ({a}, {b})','13':f'Sum.inr (Sum.inl ({a}, {b}))','23':f'Sum.inr (Sum.inr ({a}, {b}))'}[t]
L.append('/-- Pivot coordinates of the relations. -/')
L.append('def piv : Fin 12 → Margin 4 4 5 :=\n  ' + vec(['('+mg(m)+')' for m in c['psi_pivots']]) + '\n')
L.append('theorem psi_piv : ∀ s t : Fin 12, psiZ s (piv t) = if s = t then 1 else 0 := by decide +kernel\n')
L.append('theorem ell_piv_zero : True := trivial\n')
L.append('/-- The five slices have pairwise distinct zero patterns. -/')
L.append('theorem slices_distinct : ∀ k l : Fin 5, k ≠ l →\n    ∃ i : Fin 4, ∃ j : Fin 4, ¬ (onCol ellZ (i, j, k) = 0 ↔ onCol ellZ (i, j, l) = 0) := by\n  decide +kernel\n')
L.append('end R73.Cert\n')
(D/'formal/R73/Cert.lean').write_text('\n'.join(L))
print('written',sum(len(x) for x in L))
