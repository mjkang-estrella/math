"""368042: reg(I(G)^[k]) versus aim(G,k)+k for chordal graphs (arXiv:2504.11941, Conjecture 6.2).

I(G)^[k] is the square-free monomial ideal generated by the products of k-matchings, so its
Stanley-Reisner complex Delta(G,k) has faces = vertex sets F with matching number nu(G[F]) < k.
Hochster: beta_{i,W}(I) = dim H~_{|W|-i-2}(Delta_W), and Delta(G,k)_W = Delta(G[W],k); hence
  reg(I^[k]) = 2 + max{ r : H~_r(Delta(G[W],k); F) != 0, W nonempty }.
We compute top(G,k) = max{r : H~_r(Delta(G,k)) != 0} for the full vertex set and
R(G,k) = max(top(G,k)+2, max_v R(G-v,k)) recursively over the chordal list (induced subgraphs of
chordal graphs are chordal, so G-v is in the list).  Ranks are computed modulo a prime P.
aim(G,k) = max |M| over matchings M whose gap-components number r satisfies |M| <= r+k-1 (Def. 3.12;
finest partition is optimal because condition (1) forces each M_i to be a union of components).
usage: sqfree_reg.py NMAX P [n_lo]
"""
import sys, json, resource, pathlib
import numpy as np
resource.setrlimit(resource.RLIMIT_CPU, (118, 118))
L = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(L / 'scripts'))
from chordal_gen import Store

def rank_mod(M, p):
    M = M.copy() % p
    r = 0; rows, cols = M.shape
    for c in range(cols):
        if r == rows: break
        piv = np.nonzero(M[r:, c])[0]
        if piv.size == 0: continue
        i = r + piv[0]
        if i != r: M[[r, i]] = M[[i, r]]
        inv = pow(int(M[r, c]), p - 2, p)
        M[r] = (M[r] * inv) % p
        nz = np.nonzero(M[:, c])[0]
        for j in nz:
            if j != r: M[j] = (M[j] - M[j, c] * M[r]) % p
        r += 1
    return r

def matching_numbers(adj):
    n = len(adj); nu = [0] * (1 << n)
    for S in range(1, 1 << n):
        v = (S & -S).bit_length() - 1
        rest = S & ~(1 << v)
        best = nu[rest]
        nb = adj[v] & rest
        while nb:
            u = (nb & -nb).bit_length() - 1; nb &= nb - 1
            best = max(best, 1 + nu[rest & ~(1 << u)])
        nu[S] = best
    return nu

def top_homology(n, nu, k, p):
    faces = [S for S in range(1 << n) if nu[S] < k]
    if len(faces) == (1 << n):  # full simplex (incl. n>=1): acyclic
        return None
    bydim = {}
    for S in faces: bydim.setdefault(bin(S).count('1') - 1, []).append(S)
    maxd = max(bydim)
    index = {d: {S: i for i, S in enumerate(bydim[d])} for d in bydim}
    ranks = {}
    for d in range(0, maxd + 1):  # boundary C_d -> C_{d-1}
        rows = bydim[d - 1]; colsF = bydim[d]
        M = np.zeros((len(rows), len(colsF)), dtype=np.int64)
        for j, S in enumerate(colsF):
            sgn = 1; T = S
            bits = [b for b in range(n) if S >> b & 1]
            for t, b in enumerate(bits):
                M[index[d - 1][S & ~(1 << b)], j] = 1 if t % 2 == 0 else p - 1
        ranks[d] = rank_mod(M, p)
    top = None
    for r in range(-1, maxd + 1):
        dim = len(bydim[r]) - ranks.get(r, 0) - ranks.get(r + 1, 0)
        if dim > 0: top = r
    return top

def aim(adj, k):
    n = len(adj)
    edges = [(u, v) for u in range(n) for v in range(u + 1, n) if adj[u] >> v & 1]
    best = 0
    def comps(M):
        m = len(M); par = list(range(m))
        def f(x):
            while par[x] != x: par[x] = par[par[x]]; x = par[x]
            return x
        for i in range(m):
            Vi = (1 << M[i][0]) | (1 << M[i][1])
            for j in range(i + 1, m):
                Vj = (1 << M[j][0]) | (1 << M[j][1])
                if any(adj[x] & Vj for x in M[i]): par[f(i)] = f(j)
        return len({f(i) for i in range(m)})
    def rec(i, used, M):
        nonlocal best
        if M and len(M) <= comps(M) + k - 1: best = max(best, len(M))
        for t in range(i, len(edges)):
            u, v = edges[t]
            if used >> u & 1 or used >> v & 1: continue
            M.append(edges[t]); rec(t + 1, used | 1 << u | 1 << v, M); M.pop()
    rec(0, 0, [])
    return best

if __name__ == '__main__':
    NMAX = int(sys.argv[1]); P = int(sys.argv[2]); nlo = int(sys.argv[3]) if len(sys.argv) > 3 else 1
    D = L / 'outputs' / 'chordal'
    for n in range(1, NMAX + 1):
        rf = D / f'reg-n{n}-p{P}.json'
        if rf.exists(): continue
        graphs = [tuple(g) for g in json.loads((D / f'chordal-n{n}.json').read_text())]
        lo, hi = 0, len(graphs)
        if len(sys.argv) > 4 and n == NMAX:  # slice mode for the top order: argv[4] = lo:hi
            lo, hi = map(int, sys.argv[4].split(':')); rf = D / f'reg-n{n}-p{P}-slice{lo}-{hi}.json'
            if rf.exists(): continue
        prevR = json.loads((D / f'reg-n{n-1}-p{P}.json').read_text()) if n > 1 else None
        prevStore = None
        if n > 1:
            prevStore = Store()
            for g in json.loads((D / f'chordal-n{n-1}.json').read_text()): prevStore.add(list(g))
        out = []; bad = []
        for gi, G in enumerate(graphs):
            if not (lo <= gi < hi): continue
            nu = matching_numbers(G); nuG = nu[(1 << n) - 1]
            R = [None] * 10  # R[k], k=1..9
            for v in range(n):
                if n == 1: break
                keep = [u for u in range(n) if u != v]
                H = [sum(1 << keep.index(w) for w in keep if G[u] >> w & 1) for u in keep]
                idx = prevStore.find(H); assert idx is not None
                for k in range(1, 10):
                    x = prevR[idx]['R'][k]
                    if x is not None and (R[k] is None or x > R[k]): R[k] = x
            for k in range(1, nuG + 1):
                t = top_homology(n, nu, k, P)
                if t is not None and (R[k] is None or t + 2 > R[k]): R[k] = t + 2
            rec = {'adj': list(G), 'nu': nuG, 'R': R, 'aim': [None] + [aim(G, k) if k <= nuG else None for k in range(1, 10)]}
            for k in range(1, nuG + 1):
                if R[k] != rec['aim'][k] + k:
                    bad.append({'graph': gi, 'adj': list(G), 'k': k, 'reg': R[k], 'aim_plus_k': rec['aim'][k] + k})
            out.append(rec)
        rf.write_text(json.dumps(out))
        print(json.dumps({'n': n, 'P': P, 'slice': [lo, hi], 'graphs': len(out), 'mismatches': len(bad), 'first': bad[:10]}), flush=True)
