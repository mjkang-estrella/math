"""368807: emit lean/ASEPData.lean (x* table, tight cuts, encoded per-tour certificates) and re-check every
certificate exactly in Python, mirroring the Lean checker conditions k1-k7.

Encoding (base 128, little-endian digits): tl(7) | s(8) | witness a1 a2 b1 b2 | m | m x (i, j, c+64).
Order of certificates = order of List.permutations' [1..7] exported from Lean (lean/perm-order.txt)."""
import json, itertools, pathlib
from fractions import Fraction
L0 = pathlib.Path(__file__).resolve().parents[1]
n = 8
X = [[Fraction(s) for s in r] for r in json.load(open(L0 / 'outputs/asep/candidate/n8-den4.json'))['X']]
XN = [[int(4 * v) for v in r] for r in X]
assert all(Fraction(XN[i][j], 4) == X[i][j] for i in range(n) for j in range(n))
cd = json.load(open(L0 / 'outputs/asep/candidate/n8-certs.json'))
tight = [tuple(S) for S in cd['tight_cuts']]; certs = cd['certs']
order = [tuple(map(int, l.split(','))) for l in open(L0 / 'lean/perm-order.txt').read().split('\n') if l]
assert len(order) == 5040 and len(set(order)) == 5040
def fluxM(M, S): return sum(M[i][j] for i in S for j in range(n) if j not in S)
B = 128; nums = []; maxabs = 0
for tl in order:
    L = (0,) + tl
    s = [None] * n
    for k in range(n): s[L[k]] = L[(k + 1) % n]
    T = [[1 if s[i] == j else 0 for j in range(n)] for i in range(n)]
    v = {tuple(map(int, k.split(','))): c for k, c in certs[','.join(map(str, L))].items()}
    V = [[v.get((i, j), 0) for j in range(n)] for i in range(n)]
    dZ = [[XN[i][j] - 4 * T[i][j] for j in range(n)] for i in range(n)]
    wit = None
    arcs = [(i, j) for i in range(n) for j in range(n) if i != j]
    for a in arcs:
        for b in arcs:
            if dZ[a[0]][a[1]] * V[b[0]][b[1]] != dZ[b[0]][b[1]] * V[a[0]][a[1]]: wit = (a, b); break
        if wit: break
    assert wit
    es = sorted(v.items())
    # mirror Lean checks
    assert all(i != j and (XN[i][j] > 0 or s[i] == j) and c != 0 for (i, j), c in es)          # k1
    assert all(sum(c for (i, j), c in es if i == r) == 0 for r in range(n))                     # k2
    assert all(sum(c for (i, j), c in es if j == r) == 0 for r in range(n))                     # k3
    for S in tight:                                                                             # k4
        if sum(1 for i in S if s[i] not in S) == 1:
            assert sum(c for (i, j), c in es if i in S and j not in S) == 0
    assert sum(abs(c) for _, c in es) <= 64                                                     # k5
    maxabs = max(maxabs, sum(abs(c) for _, c in es))
    digits = list(tl) + s + [wit[0][0], wit[0][1], wit[1][0], wit[1][1], len(es)]
    for (i, j), c in es:
        assert -64 < c < 64
        digits += [i, j, c + 64]
    N = 0
    for dgt in reversed(digits): N = N * B + dgt
    nums.append(N)
print('certificates', len(nums), 'max l1', maxabs, 'max bits', max(x.bit_length() for x in nums))
chunks = '\n'.join(f"set_option maxRecDepth 20000 in\ndef certChunk{k} : List Nat := [\n" + ',\n'.join(map(str, nums[105 * k: 105 * (k + 1)])) + ']\n' for k in range(len(nums) // 105))
assert len(nums) % 105 == 0
rows = ',\n  '.join('[' + ','.join(map(str, r)) + ']' for r in XN)
cutsLean = ', '.join('[' + ', '.join(map(str, S)) + ']' for S in tight)
out = f"""import Mathlib.Data.Fin.Basic

/-! Data for the ASEP counterexample (generated by scripts/asep_lean_data.py). -/
namespace ASEP

/-- `4 x*` as a table of natural numbers (row `i`, column `j`). -/
def XNtab : List (List Nat) :=
 [{rows}]

/-- The eight cuts tight at `x*` (as node lists). -/
def tightCutList : List (List (Fin 8)) := [{cutsLean}]

{chunks}
/-- Encoded non-adjacency certificates, one per cyclic order `0 :: tl`, in the order of
`List.permutations' [1,2,3,4,5,6,7]`. -/
def certData : List Nat := {' ++ '.join(f'certChunk{k}' for k in range(len(nums) // 105))}

end ASEP
"""
(L0 / 'lean/ASEPData.lean').write_text(out)
print('wrote', len(out), 'bytes')
