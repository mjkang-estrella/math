"""Generate lean/KiralyCounterexample.lean from runs/cert-n11-1.json.
The certificate tree is re-derived here and only used as data; Lean's kernel checks it."""
import json, sys
d = json.load(open(sys.argv[1]))
E = d['edges']; B = d['blocker']; T = d['tree']
assert len(E) == 11 and len(B) == 36
Es = [set(x) for x in E]; Bs = [set(y) for y in B]
K = [[(v, [i for i in range(11) if Es[i] & Y == {v}]) for v in sorted(Y)] for Y in Bs]
bidx = {tuple(sorted(y)): j for j, y in enumerate(B)}

def fs(s): return '{' + ', '.join(map(str, sorted(s))) + '}'

def tree(t):
    if 'leaf' in t:
        return f'(.leaf {bidx[tuple(t["leaf"])]})'
    i = t['edge']; ch = t['children']
    vs = sorted(E[i]); assert sorted(int(k) for k in ch) == vs
    return f'(.node {i} ' + ' '.join(tree(ch[str(v)]) for v in vs) + ')'

xs_eqs = []
for i, X in enumerate(E):
    a, b, c = sorted(X)
    xs_eqs.append((i, a, b, c))

out = []
w = out.append
w(TEMPLATE_HEAD := open(sys.argv[2]).read())
w('\n/-! ## Data of the counterexample (generated by scripts/gen_lean.py) -/\n')
w('/-- The eleven edges, as a list (index `i` is edge `X' + "'" + ' i`). -/')
w('def XL : List (Finset (Fin 11)) :=\n  [' + ',\n   '.join(fs(x) for x in E) + ']\n')
w('/-- Thirty-six minimal transversals (they form the whole blocker; only membership is used). -/')
w('def YL : List (Finset (Fin 11)) :=\n  [' + ',\n   '.join(fs(y) for y in B) + ']\n')
w('/-- `DL[i]` lists the elements of edge `i` as natural numbers. -/')
w('def DL : List (List Nat) :=\n  [' + ', '.join('[' + ', '.join(map(str, sorted(x))) + ']' for x in E) + ']\n')
w('/-- `KL[j]` lists, for each `v ∈ Y j`, the edges `i` with `X i ∩ Y j = {v}`. -/')
w('def KL : List (List (Nat × List Nat)) :=\n  [' + ',\n   '.join('[' + ', '.join(f'({v}, [{", ".join(map(str, l))}])' for v, l in Kj) + ']' for Kj in K) + ']\n')
w('/-- Case-split certificate tree (branch on the value of `p` on an edge; leaves name a dead `Y j`). -/')
w('def cert : CTree :=\n  ' + tree(T) + '\n')
w(open(sys.argv[3]).read().replace('@@EDGE_EQS@@', '\n'.join(
    f'  have e{i} : y {a} + (y {b} + y {c}) = 1 := by\n'
    f'    have h := hy {i} (by norm_num)\n'
    f'    rwa [show X\' {i} = ({{{a}, {b}, {c}}} : Finset (Fin 11)) from rfl, Finset.sum_insert (by decide),\n'
    f'      Finset.sum_insert (by decide), Finset.sum_singleton] at h' for i, a, b, c in xs_eqs)))
open(sys.argv[4], 'w').write('\n'.join(out))
