"""Exact identities in Q[N,a,r,s,l]; no integer N/a instantiation or assay."""
from fractions import Fraction as Q
from math import factorial
import json

VARS = ("N", "a", "r", "s", "l")
ZERO = (0,) * len(VARS)

def const(c):
    return {} if not c else {ZERO: Q(c)}

def var(name):
    e = list(ZERO)
    e[VARS.index(name)] = 1
    return {tuple(e): Q(1)}

def add(*polys):
    out = {}
    for p in polys:
        for e, c in p.items():
            out[e] = out.get(e, Q(0)) + c
    return {e: c for e, c in out.items() if c}

def scale(p, c):
    return {e: x * c for e, x in p.items() if x * c}

def mul(p, q):
    out = {}
    for e, c in p.items():
        for f, d in q.items():
            g = tuple(x + y for x, y in zip(e, f))
            out[g] = out.get(g, Q(0)) + c * d
    return {e: c for e, c in out.items() if c}

def power(p, n):
    out = const(1)
    for _ in range(n):
        out = mul(out, p)
    return out

def equal(p, q):
    return not add(p, scale(q, -1))

N, a, r, s, ell = map(var, VARS)
checks = []
def check(name, condition):
    if not condition:
        raise AssertionError(name)
    checks.append({"identity": name, "result": "PASS"})

# Coefficients in formal Y, generated by multiplying (2j-1)^2-Y.
E = [Q(1)]
A = [E]
for j in range(1, 4):
    nxt = [Q(0)] * (j + 1)
    for h, c in enumerate(E):
        nxt[h] += (2*j-1)**2 * c
        nxt[h+1] -= c
    E = nxt
    A.append([c / (4**j * factorial(2*j+1)) for c in E])
G = []
for k in range(4):
    g = {}
    for j in range((k+1)//2, k+1):
        g = add(g, scale(power(a, 2*j), A[j][k-j]))
    G.append(g)
expected = [const(1), scale(power(a, 2), Q(1,24)),
            add(scale(power(a,4),Q(3,640)), scale(power(a,2),Q(-1,24))),
            add(scale(power(a,6),Q(5,7168)), scale(power(a,4),Q(-1,192)))]
for k in range(4):
    check(f"G_{k} from formal product coefficients", equal(G[k], expected[k]))

P = add(scale(power(a,4),9), scale(power(a,2),-80), scale(r,-80))
H = scale(P,Q(1,1920))
low = scale(add(power(a,2),mul(r,power(N,2))),Q(1,24))
check("H = 3a^4/640 - (a^2+r)/24", equal(H,
    add(scale(power(a,4),Q(3,640)),scale(add(power(a,2),r),Q(-1,24)))))
check("G_1+N^2 G_2 = low+N^2 H", equal(
    add(G[1],mul(power(N,2),G[2])),add(low,mul(power(N,2),H))))
check("third-digit lower-block identity", equal(
    add(*[mul(power(N,2*k),G[k]) for k in range(4)]),
    add(const(1),mul(power(N,2),low),mul(power(N,4),H),mul(power(N,6),G[3]))))
D = 4**3 * factorial(7)
check("D_3 = 322560", D == 322560)
check("D_3 G_k have integer coefficients", all(
    (c*D).denominator == 1 for g in G for c in g.values()))
F = scale(add(*[mul(power(N,2*k),G[k]) for k in range(4)]),D)
F_expected = add(const(322560),scale(mul(power(N,2),power(a,2)),13440),
    mul(power(N,4),add(scale(power(a,4),1512),scale(power(a,2),-13440))),
    mul(power(N,6),add(scale(power(a,6),225),scale(power(a,4),-1680))))
check("explicit F_3", equal(F,F_expected))
check("cleared third-digit polynomial on fixed s,l", equal(
    scale(add(G[3],scale(s,Q(-1,1920)),ell),D),
    add(scale(power(a,6),225),scale(power(a,4),-1680),scale(s,-168),scale(ell,322560))))
print(json.dumps({"method":"Exact sparse-polynomial identities over Q; symbolic variables only",
                  "numerical_factoring_experiments":0,
                  "scope_limit":"Does not certify floor inequalities, modular unit hypotheses, general-R proof, density, or cost; those are proved/discussed in the report.",
                  "checks":checks},indent=2))
